!c ----------------------------------------------------------------------
!c subroutine opnmbfls_sub
!c -------------------
!c
!c open mass balance files for subdomains
!c
!c written by:      Danyang Su - May 27, 25
!c
!c last modified:   -
!c
!c definition of variables:
!c
!c I --> on input   * arbitrary  - initialized  + entries expected
!c O --> on output  * arbitrary  - unaltered    + altered
!c 
!c                                                                    I O
!c passed:   -   
!c
!c common:   
!c gen.f:    integer*4:
!c           ----------
!c           icnv               = unit number, data conversion        + -
!c           ifls               = unit number, file information       + -
!c           imrt               = unit number, mass balance -         * *
!c                                             reactive transport
!c           imrt_first     = pointer - first unit number for     * +
!c                                mass balance - reactive transport
!c           imrt_last      = pointer - last unit number for      * +
!c                                mass balance - reactive transport
!c           imvs               = unit number, mass balance -         * *
!c                                             variably saturated
!c                                             flow
!c           imvs_first     = pointer - first unit number for     * +
!c                                mass balance - variably saturated
!c                                               flow
!c           imvs_last      = pointer - last unit number for      * +
!c                                mass balance - variably saturated
!c                                               flow
!c           l_prfx             = length of prefix of I/O files       + -
!c           nmb                = number of mass balance files for    + -
!c                                selected species
!c
!c           logical:
!c           --------
!c           mass_balance_rt    = .true.  -> compute mass balance     + -
!c                                           (reactive tramsport)
!c           mass_balance_vs    = .true.  -> compute mass balance     + -
!c                                           (variably saturated 
!c                                            flow)
!c
!c           character:
!c           ----------
!c           namemb(nmb)        = names of selected species           + -
!c           prefix             = prefix name for all I/O files       + -
!c           time_unit          = time unit for output -> 'years'     + -
!c                                                        'days'
!c
!c chem.f:   integer*4:
!c           ----------
!c           iaic(nsites)       = pointer array for compressed        + -
!c                                storage of surface site data
!c           nanc               = number of sorbed species            + -
!c           naq                = number of intra-aqueous kinetic     + -
!c                                reactions
!c           nc                 = number of components including h2o  + -
!c           nm                 = number of minerals                  + -
!c           ng                 = number of gases                     + -
!c           nsb                = number of sorbed species            + -
!c           nsb_ion            = number of sorbed species            + -
!c                                (ion-exchange)
!c           nsb_surf           = number of sorbed species            + -
!c                                (surface-complex)
!c           nsites             = number of surface sites             + -
!c
!c           character:
!c           ----------
!c           isotherm_type(nc)  = definition of sorption isotherm     + -    
!c                                'none' = no sorption
!c                                'linear' = linear adsorption
!c                                'freundlich' = Freundlich isotherm
!c                                'langmuir' = Langmuir isotherm
!c           nameanc(nc)        = names of sorbed species             + -
!c                                (non-competitive sorption)
!c           nameaq(naq)        = names of intra-aqueous kinetic      + -
!c                                reactions
!c           namec(nc)          = component names                     + -
!c           nameg(ng)          = names of gases                      + -
!c           namem(nm)          = mineral names                       + -
!c           namesb(nsb)        = names of sorbed species             + -
!c           namesb_ion(nsb_ion)= names of sorbed species             + -
!c                                (ion-exchange)
!c           namesb_surf(nsb_surf)= names of sorbed species           + -
!c                                  (surface-complex)
!c
!c           logical:
!c           --------
!c           noncompetitive_sorption = logical array for activation   + -  
!c                                     of noncompetitive sorption
!c                                     reactions
!c
!c local:    integer*4:
!c           ----------
!c           ianc               = counter (non-competitive sorption
!c                                         reactions)
!c           iaq                = counter (intra-aqueous kinetic 
!c                                         reactions)
!c           ic                 = counter (components)
!c           ig                 = counter (gases)
!c           im                 = counter (minerals)
!c           imb                = counter (selected species)
!c           isb                = counter (sorbed species)
!c           isites             = counter (surface sites)
!c           l_sufx             = length of file suffix
!c
!c           character:
!c           ----------
!c           suffix             = file suffix
!c
!c external: -
!c ----------------------------------------------------------------------
 
      subroutine opnmbfls_sub

#ifdef PETSC
#include <petscversion.h>
#if (PETSC_VERSION_MAJOR >= 3 && PETSC_VERSION_MINOR >= 8)
#include <petsc/finclude/petscsys.h>
      use petscsys
#endif
#endif

      use parm
      use gen
      use chem
      use dens, only : density_dependence
      use file_unit, only : lun_get, lun_set, lun_available
      use file_utility, only : check_rewind_status, readnextline      
      use module_binary_mpiio, only : binary_file_open,               &
                                      tecplot_binary_write_header,    &
                                      tecplot_binary_write_variable,  &
                                      tecplot_binary_write_zoneinfo,  &
                                      tecplot_binary_write_section
      use biol

#ifdef PETSC
      use petsc_mpi_common, only : petsc_mpi_finalize
#endif

      implicit none
#ifdef PETSC
#if (PETSC_VERSION_MAJOR >= 3 && PETSC_VERSION_MINOR >= 6 && PETSC_VERSION_MINOR < 8)
#include <petsc/finclude/petscsys.h>
#elif (PETSC_VERSION_MAJOR >= 3 && PETSC_VERSION_MINOR < 6)
#include <finclude/petscsys.h>
#endif
#endif
      
      integer :: i, j, ianc, iaq, ic, im, imb, ig, isites, isb, itmsb, &
                 istart, istop, istart2, istop2, ireac, ic2, isub,     &
                 l_sufx, l_sufx2, ierr

      character*2 :: suffix, suffix2, strtemp
      character*9 :: strl9
      character*36 :: dix_unit
      character*72 :: strl72
      character*256 :: strFilePath, prefix_sub
      character*2048 :: strbuffer2048
      character*4096 :: strbuffer
      
      integer*4 :: nvarsimvs, nvarsimrt, nvarsiarup, nvarsirup,        &
                   nvarsidix, nvarsispm, nvarsiprup, ilun, nlun,       &
                   iCdrOut, nCdrOut, nCdrOutKey, itemp, ntemp, idx
      logical :: b_rewind_valid, bflag

      external :: checkerr

!c  only the master processor needs to output mass balance
      if (rank > 0) then
        return
      end if

      if (subdomains_n < 1) then
        return
      end if 

      b_rewind_valid = .false.
      
!c  mass balance - variably saturated flow
      
      if (mass_balance_vs) then

!c  loop over subdomains

        do isub = 1, subdomains_n

          write(prefix_sub,'(a,i0)') "subdomain_", isub
          prefix_sub = trim(prefix_sub)//'/'//prefix(:l_prfx)

          imvs_first(isub) = lun_get()
        
          if (density_dependence) then
            write(ifls,'(//72a/a/72a/)') ('*',i=1,72),                 &
                 'subdomain mass balance - density dependent '//       &
                 'variably saturated flow',('*',i=1,72)
          else
            write(ifls,'(//72a/a/72a/)') ('*',i=1,72),                 &
                 'subdomain mass balance - variably saturated flow',   &
                 ('*',i=1,72)
          end if

!c  system mass

          imvs(isub) = imvs_first(isub)          
          call lun_set(imvs(isub))
        
          b_rewind_valid = check_rewind_status(trim(prefix_sub)//'_o.mvs')
          if (b_rewind_valid .and. i_append_sim > 0) then
            open(imvs(isub),file=trim(prefix_sub)//'_o.mvs',           &
                 status='unknown',form='formatted',position='rewind')
          else
            open(imvs(isub),file=trim(prefix_sub)//'_o.mvs',           &
                 status='unknown',form='formatted')
          end if
          
!c  version information
          if (i_append_sim < 1 .or. .not.b_rewind_valid) then
            if (b_writeversion_tecplot) then
              call writeversion2file(imvs(isub), "#")
            end if
          end if
          
          if (i_append_sim < 1 .or. .not.b_rewind_valid) then
            if (evaporation) then

              write(imvs(isub),'(3a)') 'title = "dataset ',trim(prefix_sub),'"'
              write(imvs(isub),'(3a)') 'variables = "time", "water mass", ',   &
                              '"water filled volume", ',                       &
                              '"vapour filled volume" '
              write(imvs(isub),'(2a)') 'zone t = "system mass - ',             &
                              ' variably saturated flow", f=point'
            else

              write(imvs(isub),'(3a)') 'title = "dataset ',trim(prefix_sub),'"'
              write(imvs(isub),'(3a)') 'variables = "time", "water mass", ',   &
                              '"water filled volume", ',                       &
                              '"gas filled volume" '
              write(imvs(isub),'(2a)') 'zone t = "system mass - ',             &
                              ' variably saturated flow", f=point'
            end if
          end if
          
          write(ifls,'(a/72a/)')'system mass',('-',i=1,72)
          write(ifls,'(a/)') trim(prefix_sub)//'_o.mvs'

          write(ifls,'(2a)')  'column   entry                           ',&
                              'unit'
          write(ifls,'(2a)')  '1        time                            ',&
                               time_unit
          write(ifls,'(2a)')  '2        water mass                      ',&
                              'kg'
          write(ifls,'(2a)')  '3        water filled volume             ',&
                              'm^3'
          write(ifls,'(2a/)') '4        air filled volume               ',&
                              'm^3'

!c  mass balance contributions

          imvs(isub) = imvs(isub)+1
          call lun_set(imvs(isub))       
            
          b_rewind_valid = check_rewind_status(trim(prefix_sub)//'_o.mvc')
          if (b_rewind_valid .and. i_append_sim > 0) then
            open(imvs(isub),file=trim(prefix_sub)//'_o.mvc',status='unknown', &
                 form='formatted',position='rewind')
          else
            open(imvs(isub),file=trim(prefix_sub)//'_o.mvc',status='unknown', &
                 form='formatted')
          end if
        
!c  version information
          if (i_append_sim < 1 .or. .not.b_rewind_valid) then
            if (b_writeversion_tecplot) then
              call writeversion2file(imvs(isub), "#")
            end if
          end if
          
          if (i_append_sim < 1 .or. .not.b_rewind_valid) then
            write(imvs(isub),'(3a)') 'title = "dataset ',trim(prefix_sub),'"'
            write(imvs(isub),'(3a)')                                     &
                  'variables = "time", "inflow", "outflow", ',           &
                  '"change in storage", ',                               &
                  '"root water uptake" '
            write(imvs(isub),'(2a)') 'zone t = "mass balance - ',        &
                                  ' variably saturated flow", f=point'
          end if

          write(ifls,'(a/72a/)')'mass balance contributions',('-',i=1,72)
          write(ifls,'(a/)') trim(prefix_sub)//'_o.mvc'

          write(ifls,'(2a)')  'column   entry                           ',&
                              'unit'
          write(ifls,'(2a)')  '1        time                            ',&
                               time_unit
          if (density_dependence) then
            write(ifls,'(2a)')  '2        total inflow                    ',&
                                'kg/day'
            write(ifls,'(2a)')  '3        total outflow                   ',&
                                'kg/day'
            write(ifls,'(2a/)') '4        change in storage               ',&
                                'kg/day'
          else
            write(ifls,'(2a)')  '2        total inflow                    ',&
                                'm^3/day'
            write(ifls,'(2a)')  '3        total outflow                   ',&
                                'm^3/day'
            write(ifls,'(2a/)') '4        change in storage               ',&
                                'm^3/day'
          end if

!c  mass balance error

          imvs(isub) = imvs(isub)+1
          call lun_set(imvs(isub))
        
          b_rewind_valid = check_rewind_status(trim(prefix_sub)//'_o.mve')
          if (b_rewind_valid .and. i_append_sim > 0) then
            open(imvs(isub),file=trim(prefix_sub)//'_o.mve',status='unknown', &
                 form='formatted',position='rewind')
          else
            open(imvs(isub),file=trim(prefix_sub)//'_o.mve',status='unknown', &
                 form='formatted')
          end if
        
!c  version information
          if (i_append_sim < 1 .or. .not.b_rewind_valid) then
            if (b_writeversion_tecplot) then
              call writeversion2file(imvs(isub), "#")
            end if
          end if
          
          if (i_append_sim < 1 .or. .not.b_rewind_valid) then
            write(imvs(isub),'(3a)') 'title = "dataset ',trim(prefix_sub),'"'
            write(imvs(isub),'(5a)') 'variables = "time", ',               &
                       '"absolute mass balance error", ',                  &
                       '"relative mass balance error", ',                  &
                       '"absolute cumulative mass balance error", ',       &
                       '"relative cumulative mass balance error" '
            write(imvs(isub),'(2a)') 'zone t = "mass balance error - ',    &
                               ' variably saturated flow", f=point'
          end if
          
          write(ifls,'(a/72a/)')'mass balance error',('-',i=1,72)
          write(ifls,'(a/)') trim(prefix_sub)//'_o.mve'

          write(ifls,'(2a)')  'column   entry                           ',&
                              'unit'
          write(ifls,'(2a)')  '1        time                            ',&
                               time_unit
          write(ifls,'(2a)')  '2        absolute mass balance error     ',&
                              'm^3'

          if (density_dependence) then
            write(ifls,'(2a)')  '3        relative mass balance error     ',&
                                '% = kg/kg in system x 100'
            write(ifls,'(2a)')  '4        accumulative absolute mass      ',&
                                'kg'
            write(ifls,'(a)')   '         balance error'
            write(ifls,'(2a)')  '5        accumulative relative mass      ',&
                                '% = kg/kg in system x 100'
            write(ifls,'(a)')   '         balance error'
          else
            write(ifls,'(2a)')  '3        relative mass balance error     ',&
                                '% = m^3/m^3 in system x 100'
            write(ifls,'(2a)')  '4        accumulative absolute mass      ',&
                                'm^3'
            write(ifls,'(a)')   '         balance error'
            write(ifls,'(2a)')  '5        accumulative relative mass      ',&
                                '% = m^3/m^3 in system x 100'
            write(ifls,'(a)')   '         balance error'
          end if

          imvs_last(isub) = imvs(isub)

        end do      ! subdomains

      end if
 
!c  mass balance - reactive transport

      if (mass_balance_rt) then

!c  loop over subdomains

        do isub = 1, subdomains_n

          write(prefix_sub,'(a,i0)') "subdomain_", isub
          prefix_sub = trim(prefix_sub)//'/'//prefix(:l_prfx)

          write(ifls,'(//72a/a/72a/)') ('*',i=1,72),                 &
               'subdomain mass balance - reactive transport',        &
               ('*',i=1,72)

!c  solute uptake by active root uptake
          if (root_uptake) then
            !c active root uptake related code
            iarup(isub) = lun_get()

            b_rewind_valid = check_rewind_status(trim(prefix_sub)//'_o.arup')
            if (b_rewind_valid .and. i_append_sim > 0) then
              open(iarup(isub),file=trim(prefix_sub)//'_o.arup',status='unknown', &
                   form='formatted',position='rewind')
            else
              open(iarup(isub),file=trim(prefix_sub)//'_o.arup',status='unknown', &
                   form='formatted')
            end if
          
!c  version information
            if (i_append_sim < 1 .or. .not.b_rewind_valid) then
              if (b_writeversion_tecplot) then
                call writeversion2file(iarup(isub), "#")
              end if
            end if

            if (i_append_sim < 1 .or. .not.b_rewind_valid) then
              write(iarup(isub),'(3a)') 'title = "dataset ',trim(prefix_sub),'"'

              strbuffer = 'variables = "time"'

              do ic = 1,nc-1
                strbuffer = trim(strbuffer)//', "'//trim(namec(ic))//&
                            ' solute uptake [mol/day]"'
              end do

              do ic = 1,nc-1
                strbuffer = trim(strbuffer)//', "'//trim(namec(ic))//&
                            ' accumulative solute uptake [mol]"'
              end do

              write(iarup(isub),'(a)') trim(strbuffer)
              write(iarup(isub),'(2a)') 'zone t = "active solute uptake - ', &
                                  'selected species", f=point'
            end if

            write(ifls,'(/2a/72a/)') 'active solute uptake - ',        &
                                     'selected species',('-',i=1,72)
            write(ifls,'(a/)') trim(prefix_sub)//'_o.arup'

            write(ifls,'(2a)')  'column   entry                           ',&
                                'unit'
            write(ifls,'(2a)')  '1        time                            ',&
                                 time_unit
            do ic = 1,nc-1
              if (ic.lt.9) then
                write(ifls,'(i1,8x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' solute uptake','mol/day'
              else
                write(ifls,'(i2,7x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' solute uptake','mol/day'
              end if
            end do

            do ic = 1,nc-1
              if (ic.lt.9) then
                write(ifls,'(i1,8x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' accumulative solute uptake','mol'
              else
                write(ifls,'(i2,7x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' accumulative solute uptake','mol'
              end if
            end do     

          end if

!c  solute uptake by passive solute uptake
          if (root_uptake .or. passive_uptake) then
            !c total passive solute uptake related code
            iprup(isub) = lun_get()

            b_rewind_valid = check_rewind_status(trim(prefix_sub)//'_o.prup')
            if (b_rewind_valid .and. i_append_sim > 0) then
              open(iprup(isub),file=trim(prefix_sub)//'_o.prup',status='unknown', &
                   form='formatted',position='rewind')
            else
              open(iprup(isub),file=trim(prefix_sub)//'_o.prup',status='unknown', &
                   form='formatted')
            end if
          
!c  version information
            if (i_append_sim < 1 .or. .not.b_rewind_valid) then
              if (b_writeversion_tecplot) then
                call writeversion2file(iprup(isub), "#")
              end if
            end if

            if (i_append_sim < 1 .or. .not.b_rewind_valid) then
              write(iprup(isub),'(3a)') 'title = "dataset ',trim(prefix_sub),'"'

              strbuffer = 'variables = "time"'

              do ic = 1,nc-1
                strbuffer = trim(strbuffer)//', "'//trim(namec(ic))//&
                            ' solute uptake [mol/day]"'
              end do

              do ic = 1,nc-1
                strbuffer = trim(strbuffer)//', "'//trim(namec(ic))//&
                            ' accumulative solute uptake [mol]"'
              end do

              write(iprup(isub),'(a)') trim(strbuffer)
              write(iprup(isub),'(2a)')                                      &
                 'zone t = "passive solute uptake - ',                 &
                 'selected species", f=point'
            end if

            write(ifls,'(/2a/72a/)') 'passive solute uptake - ',       &
                                     'selected species',('-',i=1,72)
            write(ifls,'(a/)') trim(prefix_sub)//'_o.prup'

            write(ifls,'(2a)')  'column   entry                           ', &
                                'unit'
            write(ifls,'(2a)')  '1        time                            ', &
                                 time_unit
            do ic = 1,nc-1
              if (ic.lt.9) then
                write(ifls,'(i1,8x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' solute uptake','mol/day'
              else
                write(ifls,'(i2,7x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' solute uptake','mol/day'
              end if
            end do

            do ic = 1,nc-1
              if (ic.lt.9) then
                write(ifls,'(i1,8x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' accumulative solute uptake','mol'
              else
                write(ifls,'(i2,7x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' accumulative solute uptake','mol'
              end if
            end do  

          end if

!c  total solute uptake by passive solute uptake and active solute uptake
          if (root_uptake .or. passive_uptake) then
            !c total root uptake related code
            irup(isub) = lun_get()

            b_rewind_valid = check_rewind_status(trim(prefix_sub)//'_o.rup')
            if (b_rewind_valid .and. i_append_sim > 0) then
              open(irup(isub),file=trim(prefix_sub)//'_o.rup',status='unknown', &
                   form='formatted',position='rewind')
            else
              open(irup(isub),file=trim(prefix_sub)//'_o.rup',status='unknown', &
                   form='formatted')
            end if
          
!c  version information
            if (i_append_sim < 1 .or. .not.b_rewind_valid) then
              if (b_writeversion_tecplot) then
                call writeversion2file(irup(isub), "#")
              end if
            end if

            if (i_append_sim < 1 .or. .not.b_rewind_valid) then
              write(irup(isub),'(3a)') 'title = "dataset ',trim(prefix_sub),'"'

              strbuffer = 'variables = "time"'

              do ic = 1,nc-1
                strbuffer = trim(strbuffer)//', "'//trim(namec(ic))//&
                            ' solute uptake [mol/day]"'
              end do

              do ic = 1,nc-1
                strbuffer = trim(strbuffer)//', "'//trim(namec(ic))//&
                            ' accumulative solute uptake [mol]"'
              end do
  
              write(irup(isub),'(a)') trim(strbuffer)
              write(irup(isub),'(2a)')                                       &
                 'zone t = "accumulative total solute uptake - ',      &
                 'selected species", f=point'
            end if

            write(ifls,'(/2a/72a/)')                                   &
                  'accumulative total solute uptake - ',               &
                  'selected species',('-',i=1,72)
            write(ifls,'(a/)') trim(prefix_sub)//'_o.rup'

            write(ifls,'(2a)')  'column   entry                           ', &
                                'unit'
            write(ifls,'(2a)')  '1        time                            ', &
                                 time_unit
            do ic = 1,nc-1
              if (ic.lt.9) then
                write(ifls,'(i1,8x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' solute uptake','mol/day'
              else
                write(ifls,'(i2,7x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' solute uptake','mol/day'
              end if
            end do

            do ic = 1,nc-1
              if (ic.lt.9) then
                write(ifls,'(i1,8x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' accumulative solute uptake','mol'
              else
                write(ifls,'(i2,7x,a30,2x,a)') ic+1,namec(ic)//        &
                      ' accumulative solute uptake','mol'
              end if
            end do      

          end if

!c  total system mass for components

          imrt_first(isub) = lun_get()
          nlun = 5+2*n+nmb+naq+ng+nm+ntmsb*(n+ng)+(7+nm*2)
          do ilun = 1, nlun
            call lun_set(imrt_first(isub)+ilun)
          end do

          write(ifls,'(//72a/a/72a)')               &
               ('*',i=1,72),                        &
               'mass balance - reactive transport', &
               ('*',i=1,72)

          imrt(isub) = imrt_first(isub)
        
          b_rewind_valid = check_rewind_status(trim(prefix_sub)//'_o.mas')
          if (b_rewind_valid .and. i_append_sim > 0) then
            open(imrt(isub),file=trim(prefix_sub)//'_o.mas',           &
