  !c
  !c Example of triangulation test based on scalar points
  !c
  subroutine cgal_triangulation_test_2d

    implicit none

    integer :: ix, iy, iz, n, npts, nx, ny
    type(point2d_c), allocatable :: pts(:)
    character*6 :: strformat
    character*72 :: strfile

    !c set mesh points
    nx = 10
    ny = 10
    n = nx * ny
    npts = 0
    allocate(pts(n))
    do ix = 1, nx
      do iy = 1, ny
        npts = npts + 1
        pts(npts)%x = ix
        pts(npts)%y = iy
      end do
    end do

    call cgal_set_mesh_points_tri2d(npts,pts(1:npts))
    deallocate(pts)

    !c insert constraint polyline
    npts = 0
    allocate(pts(2*nx+2*ny-4))
    do ix = 1, nx-1
      npts = npts + 1
      pts(npts)%x = ix
      pts(npts)%y = 1.0
    end do
    do iy = 1, ny-1
      npts = npts + 1
      pts(npts)%x = nx
      pts(npts)%y = iy
    end do
    do ix = 1, nx-1
      npts = npts + 1
      pts(npts)%x = nx-ix
      pts(npts)%y = ny
    end do
    do iy = 1, ny-1
      npts = npts + 1
      pts(npts)%x = 1
      pts(npts)%y = ny-iy
    end do

    call cgal_insert_constraint_polyline_tri2d(npts, pts, .false.)
    deallocate(pts)

    !c triangulation
    call cgal_make_mesh_tri2d

    !c output mesh information
    write(*,*) "-->check mesh - number of vertices: ", cgal_number_of_vertices_tri2d()
    write(*,*) "-->check mesh - number of edges: ", cgal_number_of_edges_tri2d()
    write(*,*) "-->check mesh - number of facets: ", cgal_number_of_faces_tri2d()

    !c output mesh using "off" format
    strformat = "off"
    strfile = "example/delaunay"//"."//trim(strformat)
    call cgal_output_mesh_tri2d(0, trim(strfile),trim(strformat))

    !c output mesh using "msh" format
    strformat = "msh"
    strfile = "example/delaunay"//"."//trim(strformat)
    call cgal_output_mesh_tri2d(2, trim(strfile),trim(strformat))

  end subroutine cgal_triangulation_test_2d

