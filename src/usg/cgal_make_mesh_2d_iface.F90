  !c
  !c Check the direction of the given 3 points, return true if it is counter-clockwise,
  !c   return false if it is clockwise
  !c Description of variables
  !c   (x1, y1), (x2, y2), and (x3, y3): the given 3 points
  !c   isCounterClockwise: true if the given 3 points are counter-clockwise, otherwise, false
  !c
  function isCounterClockwise(x1, y1, x2, y2, x3, y3) result(iflag)

    implicit none
    real*8, intent(in) :: x1, y1, x2, y2, x3, y3
    logical :: iflag

    real*8 :: area
    area = ((x2-x1)*(y3-y1)-(x3-x1)*(y2-y1))*0.5

    if (area > 0.0) then
      iflag = .true.
    else
      iflag = .false.
    end if

  end function isCounterClockwise

  !c
  !c Calculate equation of circle given 3 points
  !c Description of variables
  !c   (x1, y1), (x2, y2), and (x3, y3): the given 3 points
  !c   (x0, y0): calculated center point
  !c   r: calculated radius
  !c
  subroutine calculateCircle3Points(x1, y1, x2, y2, x3, y3, x0, y0, r)

    implicit none
    real*8, intent(in) :: x1, y1, x2, y2, x3, y3
    real*8, intent(out) :: x0, y0, r

    !c local variables
    real*8 :: x1y1, x2y2, x3y3, x0det, y0det
    real*8 :: r0 = 0.0d0

    x1y1 = x1*x1+y1*y1
    x2y2 = x2*x2+y2*y2
    x3y3 = x3*x3+y3*y3
    x0det = x1*(y3-y2)+x2*(y1-y3)+x3*(y2-y1)
    y0det = y1*(x3-x2)+y2*(x1-x3)+y3*(x2-x1)

    if (x0det == r0 .or. y0det == r0) then
      x0 = r0
      y0 = r0
      r  = r0
      return
    end if

    x0 = 0.5*(x1y1*(y3-y2) + x2y2*(y1-y3) + x3y3*(y2-y1))/x0det
    y0 = 0.5*(x1y1*(x3-x2) + x2y2*(x1-x3) + x3y3*(x2-x1))/y0det
    r = sqrt((x1-x0)*(x1-x0) + (y1-y0)*(y1-y0))

    return

  end subroutine  calculateCircle3Points

  !c
  !c Calculate the angle in Cartesian coordinates based on the cosine and sine value
  !c Description of variables
  !c   cosangle: input cosine value of the angle
  !c   sinangle: input sine value of the given angle
  !c   calculateAngle: return the angle in Cartesian coordinates [0-2Pi)
  !c
  function calculateAngle(cosangle, sinangle) result(angle)

    implicit none

    real*8, intent(in) :: cosangle, sinangle

    real*8 :: angle

    real*8, parameter :: pi = 3.141592653589793d0

    angle = 0.0d0

    if(cosangle >= 0.0d0 .and. sinangle >= 0.0d0) then      !quadrant 1
        angle = asin(sinangle)
    else if(cosangle < 0.0d0 .and. sinangle >= 0.0d0) then  !quadrant 2
        angle = pi - asin(sinangle)
    else if(cosangle < 0.0d0 .and. sinangle < 0.0d0) then   !quadrant 3
        angle = pi - asin(sinangle)
    else if(cosangle >= 0.0d0 .and. sinangle < 0.0d0) then  !quadrant 4
        angle = 2.0*pi + asin(sinangle)
    end if

  end function calculateAngle

  !c
  !c Partition Arc to small ones based on the given interval
  !c Description of variables
  !c   (x1, y1) and (x2, y2): the beginning and end point of the arc
  !c   (x0, y0): the center point of the arc (circle)
  !c   r: radius of the arc (circle)
  !c   isCounter: direction of the arc, if true, it is couter-clockwise, otherwise, clockwise
  !c   delt_arc: the given interval (arc length)
  !c   vp: returned all vertices, with the beginning and end point
  !c
  subroutine partitionArcPoints(x1, y1, x2, y2, x0, y0, r, isCounter,  &
                                delt_arc, vp)

    implicit none

    real*8, intent(in) :: x1, y1, x2, y2, x0, y0, r, delt_arc

    logical, intent(in) :: isCounter
    type(point2d_c), allocatable :: vp(:)

    !c local variables
    integer :: i, n
    real*8 :: xx1, yy1, xx2, yy2, cos1, sin1, cos2, sin2,              &
              angle, angle1, angle2, delt_angle, arclen
    real*8, parameter :: pi = 3.141592653589793d0

    !c convert Cartesian coordinates to Polar coordinates
    xx1 = x1 - x0
    yy1 = y1 - y0
    xx2 = x2 - x0
    yy2 = y2 - y0
    cos1 = xx1/r
    sin1 = yy1/r
    cos2 = xx2/r
    sin2 = yy2/r
    angle1 = calculateAngle(cos1, sin1)
    angle2 = calculateAngle(cos2, sin2)

    if (isCounter) then
      if (angle2 < angle1) then
        angle2 = 2.0*pi + angle2
      end if
    else
      if (angle2 > angle1) then
        angle2 = -2.0*pi + angle2
      end if
    end if

    angle = angle2 - angle1
    arclen = abs(angle*r)
    n = ceiling(arclen/delt_arc)
    delt_angle = angle/n

    if(allocated(vp)) then
      deallocate(vp)
    end if
    allocate(vp(n+1))

    do i = 0, n
      vp(i+1)%x = r*cos(angle1+delt_angle*i)+x0
      vp(i+1)%y = r*sin(angle1+delt_angle*i)+y0
    end do

  end subroutine partitionArcPoints


  !c add mixed constraint such as polyline and arc, this is mainly used for the
  !c outer boundary
  !c note: all the constraint section should be in 'open' style
  subroutine cgal_insert_constraint_mixed_circle(pts, delt_arc)

    implicit none

    !c passing parameters that will be converted to variables used in C++
    type(point2d_c), intent(in) :: pts(3)
    real*8, intent(in) :: delt_arc

    !c local variable
    real*8 :: x0, y0, r
    type(point2d_c), allocatable :: pts_tmp(:)
    logical :: iscounter

    iscounter = isCounterClockwise(pts(1)%x, pts(1)%y, pts(2)%x,       &
                                   pts(2)%y, pts(3)%x, pts(3)%y)

    call calculateCircle3Points(pts(1)%x, pts(1)%y, pts(2)%x,          &
                  pts(2)%y, pts(3)%x, pts(3)%y, x0, y0, r)

    call partitionArcPoints(pts(1)%x, pts(1)%y, pts(3)%x, pts(3)%y,    &
                  x0, y0, r, isCounter, delt_arc, pts_tmp)

    call cgal_insert_constraint_mixed_polyline(size(pts_tmp,1), pts_tmp)

  end subroutine cgal_insert_constraint_mixed_circle

