!c ----------------------------------------------------------------------
!c subroutine sorbspc
!c ------------------
!c compute concentration of sorbed species based on concentrations 
!c of primary species according to the law of mass action 
!c ion-exchange: Gaines-Thomas or Gapon convention
!c surface-complexation: constant capacitance
!c
!c written by:      Uli Mayer - July 7, 1998
!c
!c last modified:   -
!c                  
!c
!c definition of variables:
!c
!c I --> on input   * arbitrary  - initialized  + entries expected
!c O --> on output  * arbitrary  - unaltered    + altered
!c                                                                    I O
!c passed:   real*8:
!c           -------
!c           c(nc)              = concentrations of primary species   + -
!c           cec                = cation excahnge capacity            + -
!c           csb                = concentration of sorbed species     * +
!c           csb_ion            = concentration of sorbed species     * +
!c                                of ion-exchange
!c           csb_surf           = concentration of sorbed species     * +
!c                                of surface-complex
!c           eqsb(nsb)          = equilibrium constant for formation  + -
!c                                of sorbed species from primary 
!c                                species
!c           eqsb_ion(nsb_ion)  = equilibrium constant for formation  + -
!c                                of sorbed species from primary 
!c                                species (ion-exchange)
!c           eqsb_surf(nsb_surf)= equilibrium constant for formation  + -
!c                                of sorbed species from primary 
!c                                species (surface-complex)
!c           gammac(*)          = activity coefficients for primary   + -
!c                                species
!c           xnusb(*)           = stoichiometric coefficient of       + -
!c                                primary species in sorbed
!c                                species
!c           xnusb_ion(*)       = stoichiometric coefficient of       + -
!c                                primary species in sorbed
!c                                species (ion-exchange)
!c           xnusb_surf(*)      = stoichiometric coefficient of       + -
!c                                primary species in sorbed
!c                                species (surface-complex)
!c
!c           integer*4:
!c           ----------
!c           iasb(*)            = row pointer array to                + -
!c                                stoichiometric coefficients of
!c                                primary species in sorbed
!c                                species
!c           iasb_ion(*)        = row pointer array to                + -
!c                                stoichiometric coefficients of
!c                                primary species in sorbed
!c                                species (ion-exchange)
!c           iasb_surf(*)       = row pointer array to                + -
!c                                stoichiometric coefficients of
!c                                primary species in sorbed
!c                                species (surface-complex)
!c           isb                = pointer to secondary species        + -
!c           jasb(*)            = column pointer array to             + -
!c                                stoichiometric coefficients of 
!c                                primary species in sorbed
!c                                species 
!c           jasb_ion(*)        = column pointer array to             + -
!c                                stoichiometric coefficients of 
!c                                primary species in sorbed
!c                                species(ion-exchange)
!c           jasb_surf(*)       = column pointer array to             + -
!c                                stoichiometric coefficients of 
!c                                primary species in sorbed
!c                                species (surface-complex) 
!c           nsb                = number of sorbed species            + -
!c           nsb_ion            = number of sorbed species            + -
!c                                (ion-exchange)
!c           nsb_surf           = number of sorbed species            + -
!c                                (surface-complex)
!c
!c           character:
!c           ----------
!c           sorption_type    = 'gaines-thomas'                       + -
!c                              'gapon'
!c
!c
!c local:    real*8:
!c           -------
!c           r0               = constant
!c           rhalf            = constant
!c           r1               = constant
!c           r2               = constant
!c           r4               = constant
!c           term1            = intermediate term
!c           term2            = intermediate term
!c           term3            = intermediate term
!c           term4            = intermediate term
!c           term5            = intermediate term
!c
!c           integer*4:
!c           ----------
!c           i1               = counter
!c           ic               = counter (primary species)
!c           istart           = pointer
!c           istop            = pointer
!c           ksb              = counter (sorbed species)
!c
!c           logical:
!c           --------
!c           quadratic1       = .true.  -> add to quadratic term 
!c                              .false. -> add to linear term
!c           quadratic2       = .true.  -> add to quadratic term 
!c                              .false. -> add to linear term
!c           b_equivalent_ex  = .true.  -> use equivalent fraction for exchanger
!                                       -> e.g., 0.5Ca+2 + Na-X = 0.5Ca-X2 + Na+ 
!c           b_equivalent_ex  = .false. -> use equivalent fraction for sorbed species
!c           (default)                  -> e.g., Ca+2 + 2Na-X = Ca-X2 + 2Na+ 
!c
!c external: -  
!c ----------------------------------------------------------------------
  
      subroutine sorbspc(csb_ion,csb_surf,elect_surf,cec,              &
                         eqsb_ion,eqsb_surf,                           &
                         gammac,c,xnusb_ion,xnusb_surf,                &
                         iasb_ion,iasb_surf,jasb_ion,jasb_surf,        &
                         nsb_ion,nsb_surf,isb_ion,isb_surf,            &
                         sorption_type_ion,sorption_type_surf,         &
                         sorption_group,isactcexch,                    &
                         elect_correction,name_elect_correction,       &
                         nelect,dz_surf,totc,component_type,nlayer,    &
                         chargesb_surf,mol_frac_ads)
                                                                      
      implicit none
      
      real*8 :: csb_ion,csb_surf,cec,eqsb_ion,eqsb_surf,gammac,c,      &
                xnusb_ion,xnusb_surf,elect_surf,dz_surf,totc,          &
                chargesb_surf
      integer :: iasb_ion,iasb_surf,jasb_ion,jasb_surf,nsb_ion,        &
                 nsb_surf,isb_ion,isb_surf,nelect,nlayer
                                                                        
      character*72 :: sorption_type_ion,sorption_type_surf,            &
                      sorption_group,name_elect_correction                         
      character*12, dimension(*) :: component_type
                                                                        
      logical :: isactcexch, elect_correction, mol_frac_ads
                                                                        
      dimension c(*),eqsb_ion(*),eqsb_surf(*),gammac(*),               &
                xnusb_ion(*),xnusb_surf(*), iasb_ion(*),iasb_surf(*),  &
                jasb_ion(*),jasb_surf(*),elect_surf(*),totc(*)
      dimension dz_surf(nlayer,nsb_surf)
                                                                        
      real*8, parameter :: r0 = 0.0d0, rhalf = 0.5d0, r1 = 1.0d0,      &
                           r2 = 2.0d0, r3 = 3.0d0, r4 = 4.0d0,         &
                           rtol = 1.0d-10, pi = 3.141592653589793d0
      integer, parameter :: ilayer_0 = 1, ilayer_beta = 2

      logical :: quadratic1, quadratic2, cubic1, cubic2
      
      integer :: i1, ic, istart, istop, iend, ksb, ndim, nroots, nits
      
      real*8 :: term1, term2, term3, term4, term5, term6, cte, cloc, totloc

      real*8 :: ra, rb, rc, rx1, rx2, fx, fdx            !c parameter for cubic equation fx=x^3+ax^2+bx+c

      if (isb_ion.gt.0) then

!c  compute nominator
           
        quadratic1 = .false.
        cubic1 = .false.
        term1 = r1/eqsb_ion(isb_ion)
        istart = iasb_ion(isb_ion)
        istop = iasb_ion(isb_ion+1)-1
        do i1 = istart,istop
          ic = jasb_ion(i1)

          if (isactcexch) then
           term1 = term1 * (gammac(ic)*c(ic))**xnusb_ion(i1)
          else 
           term1 = term1 * c(ic)**xnusb_ion(i1)
          end if
        
          if (idnint(-xnusb_ion(i1)).eq.2) then
            quadratic1 = .true.
          else if (idnint(-xnusb_ion(i1)).eq.3) then
            cubic1 = .true. 
          end if
        end do

    !c  compute denominator
 
        if (sorption_type_ion.eq.'gapon') then

          term2 = r0

          do ksb = 1,nsb_ion
            term3 = r1/eqsb_ion(ksb)
            istart = iasb_ion(ksb)
            istop = iasb_ion(ksb+1)-1
            do i1 = istart,istop
              ic = jasb_ion(i1)
              if (isactcexch) then
                term3 = term3 * (gammac(ic)*c(ic))**xnusb_ion(i1)
              else
                term3 = term3 * c(ic)**xnusb_ion(i1)
              end if  
            end do
            term2 = term2 + term3
          end do
     
          csb_ion = cec*term1/term2

        elseif (sorption_type_ion.eq.'gaines-thomas') then

          term4 = r0
          term5 = r0
          term6 = r0

          do ksb = 1,nsb_ion

            term3 = r1/eqsb_ion(ksb)
            quadratic2 = .false.
            cubic2 = .false.

            istart = iasb_ion(ksb)
            istop = iasb_ion(ksb+1)-1

            do i1 = istart,istop

              ic = jasb_ion(i1)
              if (idnint(-xnusb_ion(i1)).eq.2) then
                quadratic2 = .true.
              else if (idnint(-xnusb_ion(i1)).eq.3) then
                cubic2 = .true.
              end if
          
              if (isactcexch) then
                 term3 = term3 * (gammac(ic)*c(ic))**xnusb_ion(i1)
              else
                 term3 = term3 * c(ic)**xnusb_ion(i1)
              end if
          
            end do

            if (cubic2) then
              term6 = term6 + term3
            else if (quadratic2) then
              term5 = term5 + term3
            else
              term4 = term4 + term3
            end if

          end do
 
          if (term6.ne.0) then            !cubic equation for tri-valent cation
            ra = term5/term6
            rb = term4/term6
            rc = -r1/term6

            !c use Newton-Raphson method to solve cubic equation instead, 
            !c x_i+1 = x_i - f(x_i)/f'(x_i)

            rx1 = r1
            rx2 = r0
            nits = 0
            do while(.true.)              
              rx2 = rx1
              fx = rx1**3+ra*rx1**2+rb*rx1+rc      !c function
              fdx = 3.0*rx1**2+2.0*ra*rx1+rb       !c derivative
              rx1 = rx1-fx/fdx
              nits = nits + 1
              if (abs(fx) < rtol .or. abs(rx1-rx2) < rtol .or. nits > 100) then
                exit                
              end if
            end do
            term2 = rx1
          else if (term5.ne.0) then
            term2 = (-term4 + (term4**r2 + r4*term5)**rhalf)/(r2*term5)
          else
            term2 = r1/term4  
          end if

          if (cubic1) then
            term2 = term2**r3
          else if (quadratic1) then
            term2 = term2**r2
          end if

          csb_ion = cec*term1*term2

        end if
       
      end if

!c  compute concentrations of sorbed species

      if (isb_surf.gt.0) then
        csb_surf=r1
!cprovi----------------------------------------------------------------------
!cprovi If electrostatic surface complexation correction is applied
!cprovi then multiply the electrostatic term in the action mass law
!cprovi----------------------------------------------------------------------
        if (elect_correction) then
          term1 = elect_surf(ilayer_0)**(-r2*dz_surf(ilayer_0,isb_surf))
          if (name_elect_correction=='triple layer model') then
            term1 = term1 * elect_surf(ilayer_beta)**(-r2*dz_surf(ilayer_beta,isb_surf))
          end if
          csb_surf = csb_surf * term1 
        end if
!cprovi----------------------------------------------------------------------
!cprovi----------------------------------------------------------------------
!cprovi----------------------------------------------------------------------
        csb_surf = csb_surf/eqsb_surf(isb_surf)

        istart = iasb_surf(isb_surf)
        iend = iasb_surf(isb_surf+1)-1
            
        do i1 = istart,iend
          ic = jasb_surf(i1) 
          cloc=c(ic)             
          ! Compute the equivalent fraction 
          if (elect_correction.and.mol_frac_ads) then
            if (component_type(ic)=='surface') then
              totloc = totc(ic)
              cloc = cloc/totloc
            end if
          end if

          csb_surf = csb_surf * (gammac(ic)*cloc)**xnusb_surf(i1)       
        end do
        
        if (elect_correction.and.mol_frac_ads) then
          !c to be checked later, totloc is assigned to the last value in the previous loop
          csb_surf = csb_surf * totloc    
        end if 

      end if        !(sorption_group)

      return
    end
