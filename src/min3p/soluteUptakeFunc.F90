!c -----------------------------------------------------------------------
!c real*8 function soluteUptakeFunc
!c -----------------------
!c compute root solute uptake for current control volume 
!c
!c written by:      Sergio A. Bea - April 17
!c
!c last modified:   Sergio A. Bea - Oct, 16
!c                  change in the alpha function applied to transpiration : mean REW profile scale used
!c
!c   definition of variables:
!c
!c I --> on input   * arbitrary  - initialized  + entries expected
!c O --> on output  * arbitrary  - unaltered    + altered
!c                                                                    I O
!c passed:   real*8:
!c
!c external: -
!c ----------------------------------------------------------------------
    real*8 function soluteUptakeFunc(qroot_j, tot_j, zpos_in, zneg_in, &
                                     root_length_dens_j, sw_in, por_in,&
                                     ic,izn)
    use biol

    implicit none
    
    ! Global variables 
    real*8, intent(in)   :: qroot_j                 ! Transpiration rate [lw/lb/day]
    integer, intent(in)  :: ic                      ! Chemical component index 
    integer, intent(in)  :: izn                     ! Zone index
    real*8, intent(in)   :: tot_j                   ! Total concentrations of the ith chemical component [mol/lw]
    real*8, intent(in)   :: root_length_dens_j      ! Root length density [m2/m3_b]
    !real*8, intent(in)   :: radius_root_j           ! Root radius [m], deprecated, DSU
    real*8, intent(in)   :: zpos_in                 !
    real*8, intent(in)   :: zneg_in                 !
    real*8, intent(in)   :: sw_in                   !
    real*8, intent(in)   :: por_in                  !
    
    ! Local variables 
    real*8, parameter    :: r0=0.0d0,           &
                            r1=1.0d0,           &
                            r2=2.0d0,           & 
                            r1000=1000.0d0,     &
                            pi=3.14159265359d0 
    real*8               :: tot_loc,                  &
                            tot_act_uptk_j,           &
                            tot_pass_uptk_j,          &
                            tot_exud_j,               &
                            root_dens,                &
                            tot_chgbal_j
    !cprovi------------------------------------------------------------------------------
    !cprovi Compute (Tj - Tj,min)
    !cprovi------------------------------------------------------------------------------
    if (tot_j<=tot_min_uptake(ic,izn)) then
      tot_loc = r0
    else
      tot_loc = tot_j - tot_min_uptake(ic,izn)
    end if
    !cprovi------------------------------------------------------------------------------
    !cprovi Compute the passive uptake
    !cprovi It depends on transpiration rate  
    !cprovi------------------------------------------------------------------------------
    tot_pass_uptk_j = qroot_j * tot_j
    !cprovi------------------------------------------------------------------------------
    !cprovi Compute root surface density
    !cprovi------------------------------------------------------------------------------
    
    !cdsu Bug here: radius_root_j is an input parameter of density dependent flow.
    !cdsu For general problem, this value is always zero.
    !cdsu Fix bug by using root length density directly.
    !root_dens = r2 * pi * radius_root_j * root_length_dens_j / r1000          ! m2/L_b
    root_dens = root_length_dens_j / r1000          ! m2/L_b
    
    !cprovi------------------------------------------------------------------------------
    !cprovi Compute the active uptake  
    !cprovi------------------------------------------------------------------------------
    tot_act_uptk_j = fm_uptake(ic,izn)/(km_uptake(ic,izn) + tot_loc)
    tot_act_uptk_j = tot_act_uptk_j + order1_uptake(ic,izn)
    tot_act_uptk_j = tot_act_uptk_j * root_dens * tot_loc
    !cprovi------------------------------------------------------------------------------
    !cprovi exudation_rate(ic,izn) => mol/m2/day
    !cprovi root_dens => m2/Lb
    !cprovi exudation => mol/Lb/day
    !cprovi------------------------------------------------------------------------------
    tot_exud_j = exudation_rate(ic,izn) * root_dens
    !cprovi------------------------------------------------------------------------------
    !cprovi Compensates the electric charge balance
    !cprovi------------------------------------------------------------------------------
    tot_chgbal_j = fchargebal_coeff(ic,izn) * sw_in * por_in * (zpos_in - zneg_in)
    !cprovi------------------------------------------------------------------------------
    !cprovi The uptake is the only mechanism if  Tj <= Tj.min 
    !cprovi (approach taken from hydrus)
    !cprovi------------------------------------------------------------------------------
    if (tot_loc==r0) then  ! Tj <= Tj.min    
      tot_act_uptk_j = r0 
    else ! Tj > Tj.min
      tot_pass_uptk_j = fac_uptake(ic,izn) * tot_pass_uptk_j
      tot_act_uptk_j = (r1-fac_uptake(ic,izn)) * tot_act_uptk_j
    end if 
    !cprovi------------------------------------------------------------------------------
    !cprovi  Compute the total uptake
    !cprovi------------------------------------------------------------------------------
    soluteUptakeFunc = tot_pass_uptk_j + tot_act_uptk_j - tot_exud_j + tot_chgbal_j
    !cprovi------------------------------------------------------------------------------
    !cprovi------------------------------------------------------------------------------
    !cprovi------------------------------------------------------------------------------
    return
    end function soluteUptakeFunc