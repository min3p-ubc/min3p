!c ----------------------------------------------------------------------
!c subroutine findname
!c -------------------
!c
!c find name in data file       
!c
!c written by:      Uli Mayer - November 10, 01
!c
!c last modified:
!c
!c definition of variables:
!c
!c I --> on input   * arbitrary  - initialized  + entries expected
!c O --> on output  * arbitrary  - unaltered    + altered
!c                                                                    I O
!c passed:   integer*4:
!c           ----------
!c           itmp
!c
!c           logical:
!c           ---------
!c           found_name
!c
!c           character:
!c           ----------
!c           name
!c
!c common:   -
!c
!c local:    character:
!c           ----------
!c           string
!c
!c external: -
!c ----------------------------------------------------------------------
 
      subroutine findname(name,itmp,found_name)

      use gen, only : rank, ilog   
      use file_utility, only : makelowercase   
#ifdef PETSC
      use petsc_mpi_common, only : petsc_mpi_finalize
#endif

      implicit none

      integer :: itmp
      logical found_name
      character*72 name,string      
      character*256 :: strbuffer

!c  rewind input file

      rewind(itmp)

!c  search for text string in input file

      found_name = .false.
      do while (.not.found_name)
        read(itmp,'(a)',err=999,end=999) strbuffer

        call makelowercase(strbuffer)

        strbuffer = adjustl(strbuffer)
        if (len(trim(strbuffer)) < 1 .or. strbuffer(1:1) == '!') then
          cycle
        else
          read(strbuffer,*,err=999,end=999) string

          if (string.eq.name) then
            found_name = .true.  
          end if
        end if

      end do

999   return

1000  backspace (unit=itmp, err=999)
      backspace (unit=itmp, err=999)
      read(itmp,'(a)') string
      if (rank == 0) then
        write(*,'(4a)') "Error in findname, error line: ",trim(string),&
              " name ",trim(name)
        write(ilog,'(4a)') "Error in findname, error line: ",trim(string),&
              " name ",trim(name)
        close(ilog)
      end if

#ifdef PETSC
      call petsc_mpi_finalize
#endif
      stop       

      end
