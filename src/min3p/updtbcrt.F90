!c ----------------------------------------------------------------------
!c subroutine updtbcrt
!c -------------------
!c
!c update boundary conditions (reactive transport) 
!c
!c first type boundary conditions: 
!c -> define zone by delineating nodes located within zone
!c
!c second type boundary condition:
!c -> define area (only on surface of solution domain)
!c
!c seepage face boundary condition:
!c -> define area (only on surface of solution domain)
!c
!c written by:      Danyang Su - March 5, 2026
!c
!c last modified:   
!c
!c definition of variables:
!c
!c I --> on input   * arbitrary  - initialized  + entries expected
!c O --> on output  * arbitrary  - unaltered    + altered
!c 
!c                                                                    I O
!c passed:   -
!c

!c ----------------------------------------------------------------------
 
      subroutine updtbcrt
 
      use parm
      use gen
      use chem
      use math_common, only : math_common_linear      
#ifdef PETSC
      use petsc_mpi_common, only : petsc_mpi_finalize
#endif

#ifdef USG
      use geometry
      use usg_mesh_data, only : nodes, cell_type, num_nodes_per_cell,  &
                                node_cells, node_num_cells,            &
                                cell2halfid, CellFaceCenter, cells,    &
                                cal_cellface_index, cell_projection,   &
                                num_faces_per_cell, CellFaceScaledNorm,&
                                is_boundary_node, num_edge_dvols,      &
                                node_to_layer_node, layer_nodes_top,   &
                                layer_nodes_bottom, CellCvolFaceArea,  &
                                get_cell_edge_cvol_id

      use read_zone_usg, only : read_zone_usg_input, type_extent_zone, &
                                type_extent_zone_box,                  &
                                type_flux_direction, flux_direction
#endif
      implicit none
      
      integer :: i, ibz, ibrt, ierr, ivol, l_string,  istart, iend,    &
                 ierrcd, iflag
      real*8 :: time_check

      external checkerr

      real*8, parameter :: r0 = 0.0d0, r1 = 1.0d0

      logical :: found,found_section,found_subsection,                 &
                 b_updt_next_only,b_updtbc_back

      character*72 :: subsection


      ierrcd = 0
      l_string = 0
      b_updt_next_only = .false.
      b_updtbc_back = .false.
      time_check = time_io

      !c adjust time to avoid round-off error when time_io is very close to the next boundary condition
      if (abs(time_io - time_bcrt) < tinytime_global) then
        time_check = time_bcrt
      end if

      !-> skip updtbcrt - a
      if ((.not. b_interpolation_bcrt .and.                            &
          time_check >= time_bcrt_prev .and. time_check < time_bcrt)   &
          .or. time_bcrt > tfinal/time_factor) then
        return
      end if

      if (.not. b_first_update_bcrt .and.                              &
         (time_check < time_bcrt_prev .or. time_check > time_bcrt)) then        
        b_updtbc_back = .true.
      end if

       
      if (time_check .ge. time_bcrt .or.                               &
          b_restart_update_bcrt .or. b_first_update_bcrt .or.          &
          b_updtbc_recall .or. b_updtbc_back) then
          
        if(rank == 0 .and. b_enable_output)  then   
                                                                       
          write(*,*)
          write(*,*) 'update boundary conditions - reactive transport'
          write(*,*) ('-',i=1,72)
          write(*,*)

          write(ilog,*)
          write(ilog,'(a)') 'update boundary conditions - reactive transport'
          write(ilog,'(72a)')('-',i=1,72)
          write(ilog,*)
        
        end if                 

!c  boundary type and zone is unchanged, just update the value
!c  note: actually the boundary type and zone cannot be changed in the current version

!c  allocate array for reading new boundary conditions
        allocate (rwork(nc-1,nbzrt), stat = ierr)
        rwork=0.0d0 
        call checkerr(ierr,'rwork',ilog)
        call memory_monitor(sizeof(rwork),'rwork',.true.)

        allocate (rwork_next(nc-1,nbzrt), stat = ierr)
        rwork_next=0.0d0 
        call checkerr(ierr,'rwork_next',ilog)
        call memory_monitor(sizeof(rwork_next),'rwork_next',.true.)

!c  assign new boundary conditions for variably-saturated flow

        if (b_first_update_bcrt .and.                                  &
            time_check.ge.time_bcrt_prev .and.                         &
            time_check.le.time_bcrt) then

          b_updt_next_only = b_first_update_bcrt
          backspace(ibcrt)

          read(ibcrt,*,err=998,end=997) time_bcrt_prev,              &
              (rwork(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)

          do while (time_check < time_bcrt_prev)
            backspace(ibcrt)
            backspace(ibcrt)
            read(ibcrt,*,err=998,end=997) time_bcrt_prev,            &
                (rwork(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)
          end do
          
          do while (time_check > time_bcrt)
            read(ibcrt,*,err=998,iostat=iflag) time_bcrt_prev,       &
                (rwork(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)
            !c end of file has reached
            if (iflag < 0) then
              time_bcrt = (tfinal+delt)/time_factor
              rwork_next = rwork              
              exit
            else
              if (time_check < time_bcrt_prev) then
                backspace(ibcrt)
                backspace(ibcrt)
                read(ibcrt,*,err=998,end=997) time_bcrt_prev,        &
                    (rwork(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)
                exit
              end if
            end if
          end do        

          read(ibcrt,*,err=998,iostat=iflag) time_bcrt,              &
              (rwork_next(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)

          !c end of file has reached
          if (iflag < 0) then
            time_bcrt = (tfinal+delt)/time_factor
            rwork_next = rwork
          end if   

        else

          backspace(ibcrt)
          read(ibcrt,*,err=998,end=997) time_bcrt_prev,              &
              (rwork(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)

          do while (time_check < time_bcrt_prev)
            backspace(ibcrt)
            backspace(ibcrt)
            read(ibcrt,*,err=998,end=997) time_bcrt_prev,            &
                (rwork(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)
          end do
          
          do while (time_check > time_bcrt)
            read(ibcrt,*,err=998,iostat=iflag) time_bcrt_prev,       &
                (rwork(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)

            !c end of file has reached
            if (iflag < 0) then
              time_bcrt = (tfinal+delt)/time_factor
              rwork_next = rwork

              exit
            else
              if (time_check < time_bcrt_prev) then
                backspace(ibcrt)
                backspace(ibcrt)
                read(ibcrt,*,err=998,end=997) time_bcrt_prev,        &
                    (rwork(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)

                exit
              end if
            end if

          end do  

          if (b_interpolation_bcrt) then
            read(ibcrt,*,err=998,iostat=iflag) time_bcrt,            &
                (rwork_next(1:bzrt_nparms(ibz),ibz),ibz=1,nbzrt)

            !c end of file has reached
            if (iflag < 0) then
              time_bcrt = (tfinal+delt)/time_factor
              rwork_next = rwork
            end if
            !c backspace, time_bcrt will be read again later
            backspace(ibcrt)
          end if

        end if

        if (update_bcrt_value_only) then
          if (nbrt > 0) then
            do ibrt = 1, nbrt
              ivol = jabrt(ibrt)

              if (ivol <= 0) then
                cycle  
              end if

              ibz = ivol2bzrt(ivol)

              if (b_interpolation_bcrt) then
                bcondrt_prev(1:bzrt_nparms(ibz),ibrt) = rwork(1:bzrt_nparms(ibz),ibz)
                bcondrt_next(1:bzrt_nparms(ibz),ibrt) = rwork_next(1:bzrt_nparms(ibz),ibz)

                bcondrt_a(1:bzrt_nparms(ibz),ibrt) = math_common_linear(           &
                                     time_bcrt_prev, time_bcrt, bzrt_nparms(ibz),  &
                                     bcondrt_prev(1:bzrt_nparms(ibz),ibrt),        &
                                     bcondrt_next(1:bzrt_nparms(ibz),ibrt),time_check)
              else
                bcondrt_a(1:bzrt_nparms(ibz),ibrt) = rwork(1:bzrt_nparms(ibz),ibz)
              end if

              if (.not. b_restart_update_bcrt) then
                if (bzrt_nparms(ibz) > 0) then
                  totcnew(1:bzrt_nparms(ibz),ivol) = bcondrt_a(1:bzrt_nparms(ibz),ibrt)
                end if
              end if

            end do
          end if
          b_first_update_bcrt = .false.
          goto 500
        end if

!c  for transient reactive transport boundary conditions, the current code only update the boundary condition values, 
!c  not the boundary type and zone, DSU 2006-03-05
500     continue

!c  deallocate workarray for reading transient boundary conditions
        call memory_monitor(-sizeof(rwork),'rwork',.true.)
        deallocate (rwork, stat = ierr)
        call checkerr(ierr,'rwork',ilog)

        call memory_monitor(-sizeof(rwork_next),'rwork_next',.true.)
        deallocate (rwork_next, stat = ierr)
        call checkerr(ierr,'rwork_next',ilog)
       
!c  restore the reading position to previous record
        if (b_updt_next_only) then
          backspace(ibcrt)
        end if

        !c  assign next read time
        if (time_bcrt < tfinal/time_factor) then
          read(ibcrt,*,err=998,end=997) time_bcrt
        end if

        return

!c  assign next read time greater than final solution time, if no more
!c  read times left and return
!cdsu replace 1.1*tfinal since tfinal can be negative

997     time_bcrt = (tfinal+1.0d100)/time_factor

        return

998     continue
        if (rank == 0) then
          write(ilog,*) 'SIMULATION TERMINATED' 
          write(ilog,*) 'error reading file ', prefix(:l_prfx)//'.bcrt'
          close(ilog)
        end if
#ifdef PETSC
        call petsc_mpi_finalize
#endif
        stop

999     continue
        if (rank == 0) then
          write(ilog,*) 'SIMULATION TERMINATED' 
          write(ilog,*) 'error reading input file, error code ', ierrcd
          write(ilog,*) 'section "',section_header(:l_string),'"'
          write(ilog,*) 'zone "', zone_name(:l_zone_name),'"'
          close(ilog)
        end if
#ifdef PETSC
        call petsc_mpi_finalize
#endif
        stop

      else if (b_interpolation_bcrt) then
        if (nbrt > 0) then
          do ibrt = 1, nbrt
            ivol = jabrt(ibrt)
            if (ivol <= 0) then
              cycle  
            end if

            ibz = ivol2bzrt(ivol)

            if (bzrt_nparms(ibz) > 0) then

              bcondrt_a(1:bzrt_nparms(ibz),ibrt) = math_common_linear( &
                        time_bcrt_prev, time_bcrt, bzrt_nparms(ibz),   &
                        bcondrt_prev(1:bzrt_nparms(ibz),ibrt),         &
                        bcondrt_next(1:bzrt_nparms(ibz),ibrt), time_check)
                
              totcnew(1:bzrt_nparms(ibz),ivol) = bcondrt_a(1:bzrt_nparms(ibz),ibrt)
            end if

          end do
        end if
      end if

      return

      end


