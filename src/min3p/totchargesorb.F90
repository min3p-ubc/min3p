!c -----------------------------------------------------------------------
!c subroutine totchargesorb
!c -------------------
!c
!c compute net electric charge balance on the surface for electrostatic correction on surface complexation 
!c models
!c
!c written by:      Sergio Andres Bea, May 2015
!c
!c last modified:   
!c subroutine totchargesorb(chargebal_surf,strion,exp_psi,csb_surf,charge_surf,    &
!c                          nsb_surf,temp,asurf,cap_surf,name_elect_correction,    &
!c                          nlayer_surf,nelect_surf,ncap_surf)
!c       
!c implicit none
!c !c----------------------------------------------------------------------------------------------------
!c !c External variables 
!!c c----------------------------------------------------------------------------------------------------
!c integer, intent(in)                                 :: nsb_surf                ! Number of surface species
!c integer, intent(in)                                 :: nelect_surf             ! Number of electrostatic terms
!c integer, intent(in)                                 :: nlayer_surf             ! Number of layers
!c integer, intent(in)                                 :: ncap_surf               ! Number of constant capacitances
!c real*8, intent(inout), dimension(nelect_surf)       :: chargebal_surf          ! Electric charge balance on the layers, [C/Lw] 
!c real*8, intent(in), dimension(nsb_surf)             :: csb_surf                ! Molality of surface complexes 
!c real*8, intent(in), dimension(nlayer_surf,nsb_surf) :: charge_surf             ! Electric charge of species in each layer
!c real*8, intent(in)                                  :: temp                    ! Temperature [K]
!c real*8, intent(in)                                  :: asurf                   ! Surface area [m2/Lb]
!c real*8, intent(in)                                  :: strion                  ! Ionic strength [mol/Lw]
!c real*8, intent(in), dimension(nelect_surf)          :: exp_psi                 ! Exponential electrostatic terms 
!c character*72, intent(in)                            :: name_elect_correction   ! Name of the electrostatic correction
!c real*8, intent(in), dimension(ncap_surf)            :: cap_surf                ! Constant capacitances  
!c !c ----------------------------------------------------------------------
!c   
subroutine totchargesorb(chargebal_surf,strion,exp_psi,csb_surf,charge_surf,    &
                         nsb_surf,temp,asurf,cap_surf,name_elect_correction,    &
                         nlayer_surf,nelect_surf,ncap_surf)
      
implicit none
!c----------------------------------------------------------------------------------------------------
!c External variables 
!c----------------------------------------------------------------------------------------------------
integer, intent(in)                                 :: nsb_surf                ! Number of surface species
integer, intent(in)                                 :: nelect_surf             ! Number of electrostatic terms
integer, intent(in)                                 :: nlayer_surf             ! Number of layers
integer, intent(in)                                 :: ncap_surf               ! Number of constant capacitances
real*8, intent(inout), dimension(nelect_surf)       :: chargebal_surf          ! Electric charge balance on the layers, [C/Lw]  
real*8, intent(in), dimension(nsb_surf)             :: csb_surf                ! Molality of surface complexes 
real*8, intent(in), dimension(nlayer_surf,nsb_surf) :: charge_surf             ! Electric charge of species in each layer
real*8, intent(in)                                  :: temp                    ! Temperature [K]
real*8, intent(in)                                  :: asurf                   ! Surface area [m2/Lb]
real*8, intent(in)                                  :: strion                  ! Ionic strength [mol/Lw]
real*8, intent(in), dimension(nelect_surf)          :: exp_psi                 ! Exponential electrostatic terms 
character*72, intent(in)                            :: name_elect_correction   ! Name of the electrostatic correction
real*8, intent(in), dimension(ncap_surf)            :: cap_surf                ! Constant capacitances  
!c----------------------------------------------------------------------------------------------------
!c Local variables and parameters
!c----------------------------------------------------------------------------------------------------
real*8, parameter :: r0=0.0d0,                 &
                     r2=2.0d0,                 &
                     faraday=96485.0d0,        &   ! Faraday constant, [C/mol e-] or [C/eq] 
                     r8000=8.0d3,              &
                     rgas=8.314d0,             &   ! Universal gas constant 
                     epsilon=78.5d0,           &
                     epsilon0=8.854d-12,       & 
                     r05=0.5d0
real*8  :: term1, term2, chargebal_sp(nlayer_surf), chargebal1, chargebal2, psi_0, psi_b, psi_d
integer :: isb, ilayer
      
if (nsb_surf>0) then
!c---------------------------------------------------------------------------------------------    
!c---------------------------------------------------------------------------------------------    
!c---------------------------------------------------------------------------------------------    
    do ilayer=1,nlayer_surf  
        chargebal_sp(ilayer)=r0
        do isb=1,nsb_surf
            chargebal_sp(ilayer) = chargebal_sp(ilayer) + charge_surf(ilayer,isb)*csb_surf(isb)
        end do
        chargebal_sp(ilayer) = faraday*chargebal_sp(ilayer)
    end do 
!c---------------------------------------------------------------------------------------------    
!c---------------------------------------------------------------------------------------------    
!c---------------------------------------------------------------------------------------------    
    if (name_elect_correction=='constant capacitance model') then
        !c------------------------------------------------------------------------
        !c For Constant Capacitance model 
        !c------------------------------------------------------------------------
        psi_0 = dlog(exp_psi(1))*r2*rgas*temp/faraday
        chargebal2 = asurf*cap_surf(1)*psi_0
        chargebal_surf(1) =  chargebal2 - chargebal_sp(1) 
    else if (name_elect_correction=='diffuse layer model') then
        !c------------------------------------------------------------------------
        !c For Diffuse Layer model
        !c------------------------------------------------------------------------
        term1 = asurf*dsqrt(r8000*epsilon*epsilon0*rgas*temp)*dsqrt(strion)  ! [C/Lw]
        term2 = dlog(exp_psi(1))
        chargebal2 = term1*dsinh(term2)
        chargebal_surf(1) =  chargebal2 - chargebal_sp(1)  
    else  
        !c------------------------------------------------------------------------
        !c For Triple Layer Model 
        !c------------------------------------------------------------------------
        psi_0 = dlog(exp_psi(1))*r2*rgas*temp/faraday
        psi_b = dlog(exp_psi(2))*r2*rgas*temp/faraday
        psi_d = dlog(exp_psi(3))*r2*rgas*temp/faraday
        !c------------------------------------------------------------------------
        !c Compute the charge balance in the 0 layer
        !c------------------------------------------------------------------------
        chargebal2 = asurf*(cap_surf(1)*(psi_0-psi_b))
        chargebal_surf(1) = chargebal2 - chargebal_sp(1)
        !c------------------------------------------------------------------------
        !c Compute the charge balance in the beta layer
        !c------------------------------------------------------------------------
        chargebal2 = asurf*(cap_surf(1)*(psi_b-psi_0) + cap_surf(2)*(psi_b-psi_d))
        chargebal_surf(2) = chargebal2 - chargebal_sp(2)
        !c------------------------------------------------------------------------
        !c Compute the charge balance in the diffuse layer
        !c------------------------------------------------------------------------
        chargebal1 = asurf*(cap_surf(2)*(psi_d-psi_b))
        term1 = -asurf*dsqrt(epsilon*epsilon0*rgas*temp*strion)  ! [C/Lw]
        term2 = dlog(exp_psi(3))
        chargebal2 = term1*dsinh(term2)  
        chargebal_surf(3) =  chargebal2 - chargebal1
    end if
!c---------------------------------------------------------------------------------------------    
!c---------------------------------------------------------------------------------------------    
!c---------------------------------------------------------------------------------------------    
end if

return
end subroutine 
