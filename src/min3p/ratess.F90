!c ----------------------------------------------------------------------
!c subroutine ratess
!c ----------------------
!c
!c compute absolute dissolution-precipitation rates for solid solutions
!c
!c sign convention: dissolution -
!c                  precipitation +
!c
!c written by:      Sergio Bea - June 15
!c
!c last modified:   Sergio Bea
!c
!c Treatment of solid solutions implemented here were based on:
!c
!c Xu, T.; Sonnenthal, E.; Spycher, N. & Pruess, K. TOUGHREACT User�s Guide: 
!c A Simulation Program for Non-isothermal Multiphase Reactive Geochemical 
!c Transport in Variably Saturated Geologic Media Earth Sciences Division, 
!c Lawrence Berkeley National Laboratory University of California, Berkeley, 
!c CA 94720., 2004
!c 
!c Lichtner, P. C. & Carey, J. W. Incorporating solid solutions in reactive 
!c transport equations using a kinetic discrete-composition approach 
!c Geochimica et Cosmochimica Acta, 2006, 70, 1356-1378
!c 
!c definition of variables:
!c ----------------------------------------------------------------------
  
subroutine ratess(ratem_loc,aream_loc,cnew_loc,cx_loc,                 &
                  gammac_loc,gammax_loc,cmold_loc,cmin_loc,            &
                  delt_loc,iter_rt_loc)
 
use parm
use chem
use gen 
#ifdef OPENMP
use omp_lib 
#endif  
 
implicit none



real*8 :: ratem_loc(*)               ! Reaction rates for all minerals               
real*8 :: aream_loc(*)                
real*8 :: cnew_loc(*)                   
real*8 :: cx_loc(*)                 
real*8 :: gammac_loc(*)             
real*8 :: gammax_loc(*)             
real*8 :: cmold_loc(*)                  ! Previous mineral concentrations
real*8 :: cmin_loc(*)
real*8 :: delt_loc                      ! Time increment
integer :: iter_rt_loc                  ! Iteration level for reactive transport

      
integer            :: im, iss, tid, i, i1, ic, ic2,       & 
                      i2, i3, ii, im2, icur, icount,      &
                      itemp, info_debug, ireac, istart,   &
                      istop, istart2, istop2, istart3,    &
                      istop3, itop, ibottom, next, ix,    &
                      iter, iter_div
real*8             :: areatot, moltot, x_i, rate,         &
                      satm1, cmoldtot, act, term1, term2, & 
                      term3, maxerror_old_loc,            &
                      maxerror_loc, satindex
real*8             :: error(nm), xss_old(nm)
real*8, parameter  :: r0 = 0.0d0, r1 = 1.0d0, r2=2.0d0, tol=1.0d-6, rbig=1.0d50  
integer, parameter :: itermax = 100, itermax_div = 5
logical            :: not_converged_loc
      

      
#ifdef OPENMP
      tid = omp_get_thread_num() + 1
#else
      tid = 1
#endif
!cprovi--------------------------------------------------------------------------------
!cprovi Compute mineral saturation index for all minerals 
!cprovi--------------------------------------------------------------------------------      
do im = 1, nm
  satm(im,tid) = satindex(cnew_loc,eqm(im,tid),gammac_loc,xnum,iam,jam,im)
end do
!cprovi--------------------------------------------------------------------------------
!cprovi Compute the molar fractions for each end-member in the solid solution
!cprovi--------------------------------------------------------------------------------
do iss = 1, nss
  moltot=r0
  areatot=r0
  satm_ss(iss,tid)=r0
  rate=r0
  cmoldtot=r0   
  do i1 = 1, nmin_ss(iss)  
    im = idmin_ss(iss,i1)  
    xss(iss,i1,tid) = satm(im,tid)
    satm_ss(iss,tid) = satm_ss(iss,tid) + satm(im,tid)
    moltot = moltot + xss(iss,i1,tid)
    areatot = areatot + aream_loc(im)
    cmoldtot = cmoldtot + (cmold_loc(im)-cmin_loc(im))   
    istart = iamd(im)
    istop = iamd(im+1)-1
    do ireac = istart,istop
      rate = rate + rated(ireac,tid)*aream_loc(im)
    end do        
  end do
  do i1 = 1, nmin_ss(iss)  
    im=idmin_ss(iss,i1)  
    xss(iss,i1,tid)=xss(iss,i1,tid)/moltot
  end do
!cprovi------------------------------------------------------------------------------------
!cprovi Compute the activity coefficients for the different end-members
!cprovi------------------------------------------------------------------------------------
  if (non_ideal_solid_solution(iss)) then
    moltot=r0
    call lambda_gugg_ss (lambda_ss(iss,:,tid), xss(iss,:,tid), gugg0_ss(iss), gugg1_ss(iss))
    do i1 = 1, nmin_ss(iss)  
      im=idmin_ss(iss,i1)
      xss(iss,i1,tid) = satm(im,tid)/lambda_ss(iss,i1,tid)
      moltot = moltot + xss(iss,i1,tid)
    end do            
    
    do i1 = 1, nmin_ss(iss)  
      xss(iss,i1,tid)=xss(iss,i1,tid)/moltot
    end do
!cprovi-------------------------------------------------------------------------------------
!cprovi Iterative process to compute activity coefficients      
!cprovi-------------------------------------------------------------------------------------    
    iter = 0     
        
    iter_div = 0
        
    not_converged_loc=.true. 
        
    maxerror_old_loc = rbig 
        
    do while (not_converged_loc)   

        iter = iter + 1 
        do i1 = 1, nmin_ss(iss)
          xss_old(i1)=xss(iss,i1,tid)
        end do
 
        call lambda_gugg_ss (lambda_ss(iss,:,tid), xss(iss,:,tid), gugg0_ss(iss), gugg1_ss(iss))
        moltot=r0
        do i1 = 1, nmin_ss(iss)  
          im=idmin_ss(iss,i1)  
          xss(iss,i1,tid)=satm(im,tid)/lambda_ss(iss,i1,tid)
          moltot=moltot+xss(iss,i1,tid)
        end do 
 
        do i1 = 1, nmin_ss(iss)  
          im=idmin_ss(iss,i1)  
          xss(iss,i1,tid)=xss(iss,i1,tid)/moltot
          error(i1)=dabs((xss_old(i1) - xss(iss,i1,tid))/xss_old(i1))
        end do 
            
        maxerror_loc=maxval(error)
            
        if (maxerror_loc>maxerror_old_loc) then
          iter_div = iter_div + 1  
        end if 
            
        if (maxerror_loc<=tol.or.iter>itermax.or.iter_div>itermax_div) then
          not_converged_loc=.false.
        end if 
            
        maxerror_old_loc = maxerror_loc

    end do

    satm_ss(iss,tid)=r1  
    do i1 = 1, nmin_ss(iss)  
        im=idmin_ss(iss,i1)  
        act=xss(iss,i1,tid)*lambda_ss(iss,i1,tid)
        satm_ss(iss,tid)=satm_ss(iss,tid)*(satm(im,tid)/act)**xss(iss,i1,tid)
    end do  
      
  else 
    lambda_ss(iss,:,tid)=r1
  end if
!cprovi------------------------------------------------------------------------------------
!cprovi Multiply the reaction rates by the affinity term 
!cprovi------------------------------------------------------------------------------------
  rate = -rate*(r1-satm_ss(iss,tid))
!cprovi------------------------------------------------------------------------------------
!cprovi Scale the reaction rate in order to ensure the mass proportion in the solid 
!cprovi------------------------------------------------------------------------------------
  do i1 = 1, nmin_ss(iss)  
    im=idmin_ss(iss,i1) 
    x_i = xss(iss,i1,tid) 
    if (chemical_zoning_ss(iss)) then
      term1 = r0
      term3 = r0
    else 
      term1= x_i*cmoldtot/delt_loc
      term3 = (cmold_loc(im)-cmin_loc(im))/delt_loc
    end if 
    term2 = x_i*rate
    ratem_loc(im) = term1 + term2 - term3 
  end do
    
end do 

return
end subroutine
!----------------------------------------------------------------------------------------------
!----------------------------------------------------------------------------------------------
!----------------------------------------------------------------------------------------------
! Guggenheim activity coefficients for binary non-ideal solid solutions 
!----------------------------------------------------------------------------------------------
!----------------------------------------------------------------------------------------------
!----------------------------------------------------------------------------------------------
subroutine lambda_gugg_ss(lambda_gugg,xss,gugg0ss,gugg1ss)

implicit none
real*8, intent(inout)  :: lambda_gugg(2)
real*8, intent(in)     :: xss(2)
real*8, intent(in)     :: gugg0ss
real*8, intent(in)     :: gugg1ss

real*8, parameter :: r1=1.0d0, r0=0.0d0, r2=2.0d0, r3=3.0d0, r4=4.0d0

lambda_gugg(1)=xss(2)*xss(2)*(gugg0ss-gugg1ss*(r4*xss(1)-r1))
lambda_gugg(2)=xss(1)*xss(1)*(gugg0ss+gugg1ss*(r4*xss(2)-r1))

lambda_gugg(1)=dexp(lambda_gugg(1))
lambda_gugg(2)=dexp(lambda_gugg(2))


return
end subroutine 
