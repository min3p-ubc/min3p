      subroutine test_fcn(m,n,x,r)
      use test_MOD, only: icase,nfcn
      implicit none
      integer i,j,j2,j4,m,n
      real*8 a,f1,f2,h,r(m),test_ex,test_cheb,theta,ti,total,ui,vi,wi,x(n),yi
      real*8 bard(15)
      data bard                                                        &
       /.14d0,.18d0,.22d0,.25d0,.29d0,.32d0,.35d0,                     &
       .39d0,.37d0,.58d0,.73d0,.96d0,1.34d0,2.10d0,4.39d0/
      real*8 gaussi(15)
      data gaussi                                                      &
       /.0009d0,.0044d0,.0175d0,.0540d0,.1295d0,                       &
        .2420d0,.3521d0,.3989d0,.3521d0,.2420d0,.1295d0,               &
        .0540d0,.0175d0,.0044d0,.0009d0/
      integer meyer(16)
      data meyer                                                       &
       /34780,28610,23650,19630,16370,13720,11540,9744,                &
       8261,7030,6005,5147,4427,3820,3307,2872/
      real*8 kowyi(11)
      data kowyi                                                       &
       /.1957d0,.1947d0,.1735d0,.1600d0,.0844d0,                       &
       .0627d0,.0456d0,.0342d0,.0323d0,.0235d0,.0246d0/
      real*8 kowui(11)
      data kowui                                                       &
       /4.d0,2.d0,1.d0,.5d0,.25d0,                                     &
       .1670d0,.1250d0,.1000d0,.0833d0,.0714d0,.0625d0/
      real*8 osbor1(33)
      data osbor1                                                      &
       /.844d0,.908d0,.932d0,.936d0,.925d0,.908d0,.881d0,.850d0,       &
       .818d0,.784d0,.751d0,.718d0,.685d0,.658d0,.628d0,.603d0,        &
       .580d0,.558d0,.538d0,.522d0,.506d0,.490d0,.478d0,.467d0,        &
       .457d0,.448d0,.438d0,.431d0,.424d0,.420d0,.414d0,.411d0,.406d0/
      real*8 osbor2(65)
      data osbor2                                                      &
       /1.366d0,1.191d0,1.112d0,1.013d0,.991d0,                        &
       .885d0,.831d0,.847d0,.786d0,.725d0,                             &
       .746d0,.679d0,.608d0,.655d0,.616d0,                             &
       .606d0,.602d0,.626d0,.651d0,.724d0,                             &
       .649d0,.649d0,.694d0,.644d0,.624d0,                             &
       .661d0,.612d0,.558d0,.533d0,.495d0,                             &
       .500d0,.423d0,.395d0,.375d0,.372d0,                             &
       .391d0,.396d0,.405d0,.428d0,.429d0,                             &
       .523d0,.562d0,.607d0,.653d0,.672d0,                             &
       .708d0,.633d0,.668d0,.645d0,.632d0,                             &
       .591d0,.559d0,.597d0,.625d0,.739d0,                             &
       .710d0,.729d0,.720d0,.636d0,.581d0,                             &
       .428d0,.292d0,.162d0,.098d0,.054d0/
      real*8, save :: ONE=1
      real*8 pi
      select case(icase)
      case(1) ! Rosenblock n=m=2
         r(1)= 10*(x(2)-x(1)**2)
         r(2)= 1-x(1)
      case(2) ! Freudenstein and Roth n=m=2
         r(1)=-13+x(1)+((5-x(2))*x(2)-2)*x(2)
         r(2)=-29+x(1)+((x(2)+1)*x(2)-14)*x(2)
      case(3) ! Powell badly scaled n=m=2
         r(1) = 10000*x(1)*x(2)-1
         r(2) = test_ex(-x(1))+test_ex(-x(2))-1.0001q0
      case(4) ! Brown badly scaled n=2 m=3
         r(1) = x(1)-1000000
         r(2) = x(2)-2*ONE/10**6
         r(3) = x(1)*x(2)-2
      case(5) ! Beale n=2 m=3
         r(1) = 1.5q0-x(1)*(1-x(2))
         r(2) = 2.25q0-x(1)*(1-x(2)**2)
         r(3) = 2.625q0-x(1)*(1-x(2)**3)
      case(6) ! Jennrick and Sampson n=2
         do i=1,m
            r(i)=2+2*i-test_ex(i*x(1))-test_ex(i*x(2))
         enddo
      case(7) ! Helical valley n=m=3
         pi=4*atan(ONE)
         theta=atan2(x(2),x(1))/(2*pi)
         r(1) = 10*(x(3)-10*theta)
         r(2) = 10*(sqrt(x(1)**2+x(2)**2)-1)
         r(3) = x(3)
      case(8) ! Bard n=3 m=15
         do i=1,m
            ui = i
            vi = 16-i
            if(ui.lt.vi) then
               wi=ui
            else
               wi=vi
            endif
            r(i) = bard(i)-(x(1)+ui/(vi*x(2)+wi*x(3)))
         enddo
      case(9) ! Gaussian n=3 m=15
         do i=1,m
            ti=ONE*(8-i)/2
            r(i) = x(1)*test_ex(-x(2)*(ti-x(3))**2/2)-gaussi(i)
         enddo
      case(10) ! Meyer n=3 m=16
         do i=1,m
            ti=45+5*i
            r(i)= x(1)*test_ex(x(2)/(ti+x(3)))-meyer(i)
         enddo
      case(11) ! Gulf research and development n=3 m<101
         do i=1,m
            ti=i*ONE/100
            yi=abs((-50*log(ti))**(2*ONE/3)+25-x(2))
            r(i)=test_ex(-yi**x(3)/x(1))-ti
         enddo
      case(12) ! Box three dimensional n=3
         do i=1,m
            ti=ONE*i/10
            r(i)= test_ex(-ti*x(1))-test_ex(-ti*x(2))-                 &
                  x(3)*(test_ex(-ti)-test_ex(-10*ti))
         enddo
      case(13) ! Powell singular n=m=4
         r(1)=x(1)+10*x(2)
         r(2)=sqrt(5*ONE)*(x(3)-x(4))
         r(3)=(x(2)-2*x(3))**2
         r(4)=sqrt(10*ONE)*(x(1)-x(4))**2
      case(14) ! Wood n=4 m=6
         r(1)=10.d0*(x(2)-x(1)**2)
         r(2)=1-x(1)
         r(3)=sqrt(90*ONE)*(x(4)-x(3)**2)
         r(4)=1-x(3)
         r(5)=sqrt(10*ONE)*(x(2)+x(4)-2)
         r(6)=(x(2)-x(4))/sqrt(10*ONE)
      case(15) ! Kowalik and Osborne n=4 m=11
         do i=1,m
            r(i) = kowyi(i)-x(1)*(kowui(i)**2+kowui(i)*x(2))/          &
                   (kowui(i)**2+kowui(i)*x(3)+x(4))
         enddo
      case(16) ! Brown and Dennis n=4
         do i=1,m
            ti=ONE*i/5
            r(i) = (x(1)+ti*x(2)-test_ex(ti))**2 +                     &
                   (x(3)+x(4)*sin(ti)-cos(ti))**2
         enddo
      case(17) ! Osborne 1 n=5 m=33
         do i=1,m
            ti=10*ONE*(i-1)
            r(i) = osbor1(i)-(x(1)+x(2)*test_ex(-ti*x(4)) +            &
                   x(3)*test_ex(-ti*x(5)))
         enddo
      case(18) ! Biggs EXP6 n=6
         do i=1,m
            ti=ONE*i/10
            yi = test_ex(-ti)-5*test_ex(-10*ti)+3*test_ex(-4*ti)
            r(i) = x(3)*test_ex(-ti*x(1))-x(4)*test_ex(-ti*x(2)) +     &
                   x(6)*test_ex(-ti*x(5))-yi
         enddo
      case(19) ! Osborne 2 n=11 m=65
         do i=1,m
            ti=(i-1)*ONE/10
            r(i) = osbor2(i)-(x(1)*test_ex(-ti*x(5))  +                &
                   x(2)*test_ex(-(ti-x(9))**2*x(6))   +                &
                   x(3)*test_ex(-(ti-x(10))**2*x(7))  +                &
                   x(4)*test_ex(-(ti-x(11))**2*x(8)))
         enddo
      case(20) ! Watson n>1 m=31, n=9
         r(30)=x(1)
         r(31)=x(2)-x(1)**2-1
         do i=1,29
            yi=0
            ui=x(1)
            ti=i*ONE/29
            do j=2,n
               ui=ui+x(j)*ti**(j-1)
               yi=yi+(j-1)*x(j)*ti**(j-2)
            enddo
            r(i)=yi-ui**2-1
         enddo
      case(21) ! Extended Rosenblock n=m=2k
         do j2=1,6
            r(2*j2-1)=10*(x(2*j2)-x(2*j2-1)**2)
            r(2*j2)=1-x(2*j2-1)
         enddo
      case(22) ! Extended Powell singular n=m=4k
         do j4=1,m/4
            r(4*j4-3)=x(4*j4-3)+10*x(4*j4-2)
            r(4*j4-2)=sqrt(5*ONE)*(x(4*j4-1)-x(4*j4))
            r(4*j4-1)=(x(4*j4-2)-2*x(4*j4-1))**2
            r(4*j4)=sqrt(10*ONE)*(x(4*j4-3)-x(4*j4))
         enddo
      case(23) ! Penalty I m=n+1
         total=0
         do j=1,n
            r(j)=sqrt(ONE/10**5)*(x(j)-1)
            total=total+x(j)**2
         enddo
         r(m)=total-ONE/4
      case(24) ! Penalty II m=2n
         r(1)=x(1)-2*ONE/10
         total=0
         do j=1,n
            total=total+(n-j+1)*x(j)**2
         enddo
         r(2)=total-1
         a=sqrt(ONE/10**5)
         do j=2,n
            yi = test_ex(j*ONE/10)+test_ex((j-1)*ONE/10)
            f1 = a*(test_ex(x(j)/10)+test_ex(x(j-1)/10)-yi)
            f2 = a*(test_ex(x(j)/10)-test_ex(-ONE/10))
            r(2*j-1)=f1
            r(2*j)=f2
         enddo
      case(25) ! Variably dimensioned m=n+2
         do j=1,n
            r(j)=x(j)-1
         enddo
         total=0
         do j=1,n
            total=total+j*(x(j)-1)
         enddo
         r(n+1)=total
         r(n+2)=total**2
      case(26) ! Trigonmetric m=n
         total=0
         do j=1,n
            total=total+cos(x(j))
         enddo
         do i=1,m
            r(i)=n-total+i*(1-cos(x(i)))-sin(x(i))
         enddo
      case(27) ! Brown almost-linear m=n
         total=0
         do j=1,n
            total=total+x(j)
         enddo
         do j=1,n-1
            r(j)=total-(n+1)+x(j)
         enddo
         r(n)=x(1)-1
      case(28) ! Discrete boundary value m=n
         h=ONE/(n+1)
         do j=1,n
            r(j)=2*x(j)+h**2*(x(j)+j*h+1)**3/2
            if(j.gt.1) r(j)=r(j)-x(j-1)
            if(j.lt.n) r(j)=r(j)-x(j+1)
         enddo
      case(29) ! Discrete integral equation m=n
         h=ONE/(n+1)
         yi=0
         do j=1,n
            ui=0
            do i=j+1,n
               ti=i*h
               ui=ui+(1-ti)*(x(i)+ti+1)**3
            enddo
            ti=j*h
            yi=yi+ti*(x(j)+ti+1)**3
            r(j)=x(j)+h*((1-ti)*yi+ti*ui)/2
         enddo
      case(30) ! Broyden tridiagonal m=n
         do j=1,n
            r(j)=(3-2*x(j))*x(j)+1
            if(j.gt.1) r(j)=r(j)-x(j-1)
            if(j.lt.n) r(j)=r(j)-2*x(j+1)
         enddo
      case(31) ! Broyden banded m=n
         do j=1,n
            yi=0
            do i=j-5,j+1
            if(i.gt.1.and.i.lt.n) then
               if(i.ne.j) yi=yi+x(i)*(1+x(i))
            endif
         enddo
         r(j)=x(j)*(2+5*x(j)**2)+1-yi
         enddo
      case(32) ! Linear function--full rank
         total=0
         do j=1,n
            total=total+x(j)
         enddo
         yi=2*total/m
         do j=1,n
            r(j)=x(j)-yi-1
         enddo
         do i=n+1,m
            r(i)=-yi-1
         enddo
      case(33) ! Linear--rank 1
         total=0
         do j=1,n
         total=total+x(j)*j
         enddo
         do i=1,m
            r(i)=i*total-1
         enddo
      case(34) ! Linear function--rank 1 with zero columns and rows
         total=0
         do j=1,n-2
            total=total+x(j)*j
         enddo
         do i=1,m-2
            r(i)=i*total-1
         enddo
         r(m-1)=-1
         r(m)=-1
      case(35) ! Chebyquad 1/n Sum j=1,n Ti(x(j)) - Int 0 to 1 Ti(x) dx = 0
         do i=1,m
         yi=0
         do j=1,n
            yi=yi+test_cheb(i,x(j))
         enddo
         r(i)=yi/n
         if(mod(i,2).eq.0) r(i)=r(i)+ONE/(i**2-1)
         enddo
      case(36) ! Modified Beale (problem 5) that required many evaluations
         r(1) = ONE/2-x(1)*(1-x(2))
         r(2) = 3-x(1)*(1-x(2)**2)
         r(3) = 5-x(1)*(1-x(2)**3)
      case(37) ! Rosenblock (problem 1) changed to single residual (m=1)
         r(1)=sqrt((10*(x(2)-x(1)**2))**2+(1-x(1))**2)
      end select
      nfcn=nfcn+1
      end
!-----------------------------------------------------------------------
      real*8 function test_ex(x)
! substitute exponential to avoid overflow
      implicit none
      intrinsic exp
      real*8 x
! in order to prevent single precision overflow
      if(x.lt.87d0) then
         test_ex=exp(x)
         return
      endif
      test_ex=exp(87d0)
      end
!-----------------------------------------------------------------------
      real*8 function test_cheb(i,x)
! substitute chebychev function with penalty for abs(x) > 1
      implicit none
      intrinsic acos,cos
      integer i
      real*8 x
      if(abs(x).gt.1) then
         test_cheb=1000000
         return
      endif
      test_cheb=cos(i*acos(x))
      end
