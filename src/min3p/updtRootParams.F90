!c ----------------------------------------------------------------------
!c subroutine updtRootParams
!c -------------------
!c
!c physical parameters for root related parameters
!c
!c written by:      Sbea
!c
!c last modified:   
!c                  Danyang Su, format change and fix bug in time series
!c
!c ----------------------------------------------------------------------

    subroutine updtRootParams
 
    use parm
    use gen
    use phys
    use biol
#ifdef OPENMP
    use omp_lib 
#endif 
#ifdef PETSC
    use petsc_mpi_common, only : petsc_mpi_finalize
#endif

    implicit none

    integer :: ivol, izn, icount, iflag
    logical :: flag_valid
    real*8 :: rdummy
    real*8, parameter :: r0 = 0.0d0

    if (rootparam_trans .and. time_io >= time_root .and. &
        time_io < tfinal/time_factor) then

      !cdsu locate the data line
      icount = 0
      iflag = 0
      rdummy = time_root
      flag_valid = .false.
      do while (time_io >= rdummy)
        read(itransroot,*,err=999,iostat=iflag) rdummy

        icount = icount + 1

        !c the end of file, or the next line is negative (indicates the end of file)
        if (iflag < 0 .or. rdummy < r0) then
          time_root = (tfinal+delt)/time_factor
          if (icount > 1) then
            backspace(itransroot)
            backspace(itransroot)
            flag_valid = .true.
          end if
          exit
        end if

        !c next time found
        if (time_io < rdummy) then
          time_root = rdummy
          backspace(itransroot)
          if (icount > 1) then
            backspace(itransroot)
            flag_valid = .true.
          end if
          exit
        end if
      end do

      !cprovi------------------------------------------------------------------------------------------------------
      !cprovi Time depends on time units used in the problem
      !cprovi------------------------------------------------------------------------------------------------------   
      if (flag_valid) then
        read(itransroot,*,err=999,end=999) rdummy,(rootlengthdens(izn),rew0(izn),p1(izn),izn=1,nzn) 
#ifdef OPENMP
    !$omp parallel                                                    &
    !$omp if (nngl > numofloops_thred_global)                         &
    !$omp num_threads(numofthreads_global)                            &
    !$omp default(shared)                                             &
    !$omp private (ivol,izn)
    !$omp do schedule(static)
#endif
        do ivol = 1, nngl
          izn = mpropvs(ivol)
          rld(ivol) = rootlengthdens(izn)  ! [m/m3]
        enddo
#ifdef OPENMP
    !$omp end do
    !$omp end parallel
#endif

      end if
  
    end if       
  
    return

999 continue
    if(rank == 0) then
       write(ilog,*) 'SIMULATION TERMINATED' 
       write(ilog,*) 'error reading file ', prefix(:l_prfx)//'.transroot'
       close(ilog)
    end if
#ifdef PETSC
    call petsc_mpi_finalize
#endif
    stop

    return

    end
