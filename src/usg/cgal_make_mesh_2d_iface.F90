    real*8, intent(in) :: shape_bound, max_edge

    !c local variables
    real(c_double) :: shape_bound_c, max_edge_c

    shape_bound_c = shape_bound
    max_edge_c = max_edge

    call set_criteria(shape_bound_c, max_edge_c)

  end subroutine cgal_set_criteria

  !c make/refine mesh using constrained delaunay triangulation
  subroutine cgal_make_refine_mesh()

    implicit none

    call make_refine_mesh()

  end subroutine cgal_make_refine_mesh

  !c optimize mesh using lloyd_optimize_mesh_2 method
  subroutine cgal_optimize_mesh(iteration)

    implicit none

    !c passing parameters that will be converted to variables used in C++
    integer, intent(in) :: iteration

    !c local variables
    integer(c_int) :: iteration_c

    iteration_c = iteration

    call optimize_mesh(iteration_c)

  end subroutine cgal_optimize_mesh

  !c write mesh to file
  subroutine cgal_output_mesh(itype, strfile,strformat)

    implicit none

    integer(c_int) :: itype
    character(len=*) :: strfile, strformat
    character(kind=c_char, len=1), dimension(256) :: strfile_cc, strformat_cc

    integer(c_int) :: i, nstrfile, nstrformat

    nstrfile = len_trim(strfile)
    nstrformat = len_trim(strformat)

    do i = 1, nstrfile
      strfile_cc(i) = strfile(i:i)
    end do

    do i = 1, nstrformat
      strformat_cc(i) = strformat(i:i)
    end do

    call set_coordinate_type(itype)
    call output_mesh(nstrfile,strfile_cc,nstrformat,strformat_cc)

  end subroutine cgal_output_mesh

