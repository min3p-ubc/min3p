  !c add mixed constraint such as polyline and arc, this is mainly used for the
  !c outer boundary
  !c note: all the constraint section should be in 'open' style
  subroutine cgal_insert_constraint_mixed_polyline(n, pts)

    implicit none

    !c passing parameters that will be converted to variables used in C++
    integer :: n
    type(point2d_c), intent(in) :: pts(n)

    !c local variable
    integer :: i
    real*8, parameter :: rsmall = 1.0d-8

    do i = 1, n
      if (num_points_mixed > 0) then
        !c check if new added point is same as previous one
        if (distance(points_mixed(num_points_mixed),pts(i)) > rsmall) then
          num_points_mixed = num_points_mixed + 1
          points_mixed(num_points_mixed) = pts(i)
        end if
        !c check if the last point is same as first point
        if (distance(points_mixed(num_points_mixed),                   &
                     points_mixed(1)) < rsmall) then
          num_points_mixed = num_points_mixed - 1
        end if

      else
        num_points_mixed = num_points_mixed + 1
        points_mixed(num_points_mixed) = pts(i)
      end if
    end do

  end subroutine cgal_insert_constraint_mixed_polyline

  !c add mixed constraint such as polyline and arc, this is mainly used for the
  !c outer boundary
  !c note: all the constraint section should be in 'open' style
  subroutine cgal_insert_constraint_mixed_polyline_n(n, pts, ivalue)

    implicit none

    !c passing parameters that will be converted to variables used in C++
    integer :: n
    type(point2d_c), intent(in) :: pts(n)
    integer, intent(in) :: ivalue(n)

    !c local variable
    integer :: i, j, k
    real*8 :: dist_tmp, deltx, delty
    type(point2d_c), allocatable :: pts_tmp(:)

    do i = 1, n-1
      dist_tmp = distance(pts(i),pts(i+1))
      j = ivalue(i)
      deltx = (pts(i+1)%x-pts(i)%x)/j
      delty = (pts(i+1)%y-pts(i)%y)/j
      allocate(pts_tmp(j+1))
      pts_tmp(1) = pts(i)
      do k = 1, j
        pts_tmp(k+1)%x = pts_tmp(1)%x+k*deltx
        pts_tmp(k+1)%y = pts_tmp(1)%y+k*delty
      end do
      call cgal_insert_constraint_mixed_polyline(j+1, pts_tmp)
      deallocate(pts_tmp)
    end do


  end subroutine cgal_insert_constraint_mixed_polyline_n

