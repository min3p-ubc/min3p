#ifdef CGAL

module cgal_triangulation_3d_iface

  !c this is feature of Fortran 2003
  use iso_c_binding

  use geometry_definition

  implicit none

  private

  public cgal_triangulation_test_3d, cgal_set_mesh_points_3d,          &
         cgal_triangulation_3d, cgal_output_mesh_3d,                   &
         number_of_vertices_3d, number_of_edges_3d,                    &
         number_of_facets_3d, number_of_cells_3d


  !c interface binding to CGAL c++ code
  interface

    !c allocate storage for points
    function allocate_storage_point3d(n) result(iresult) bind(C,name="allocate_storage_point3d")
      import c_int, c_ptr
      implicit none
      integer(c_int),value :: n
      type(c_ptr) :: iresult
    end function allocate_storage_point3d

    !c deallocate storage for points
    subroutine deallocate_storage(ptr) bind(C,name="deallocate_storage")
      import c_ptr
      implicit none
      type(c_ptr), intent(in), value :: ptr
    end subroutine deallocate_storage


    !c set points with index
    subroutine set_mesh_points_3d(n,pts) bind(C,name="set_mesh_points_3d")
      import c_int, c_ptr
      implicit none
      integer(c_int),value :: n
      type(c_ptr), intent(in), value :: pts
    end subroutine set_mesh_points_3d

    !c triangulation
    subroutine triangulation_3d() bind(C,name="triangulation_3d")
      implicit none
    end subroutine triangulation_3d

    !c number of vertices in the mesh
    function number_of_vertices_3d() result(n) bind(C,name="number_of_vertices_3d")
      import c_int
      implicit none
      integer(c_int) :: n
    end function number_of_vertices_3d

    !c number of finite edges in the mesh
    function number_of_edges_3d() result(n) bind(C,name="number_of_finite_edges_3d")
      import c_int
      implicit none
      integer(c_int) :: n
    end function number_of_edges_3d

    !c number of finite facets in the mesh
    function number_of_facets_3d() result(n) bind(C,name="number_of_finite_facets_3d")
      import c_int
      implicit none
      integer(c_int) :: n
    end function number_of_facets_3d

    !c number of cells in the mesh
    function number_of_cells_3d() result(n) bind(C,name="number_of_finite_cells_3d")
      import c_int
      implicit none
      integer(c_int) :: n
    end function number_of_cells_3d

    !c write mesh to file
    subroutine output_triangulation_3d(nstrfile,strfile,nstrformat,strformat) bind(C,name="output_triangulation_3d")
      import c_int, c_char
      implicit none
      integer(c_int), value :: nstrfile, nstrformat
      character(kind=c_char, len=1), dimension(nstrfile) :: strfile
      character(kind=c_char, len=1), dimension(nstrformat) :: strformat
    end subroutine output_triangulation_3d

  end interface

  !c interface of fortran code

contains
  !c set mesh points
  subroutine cgal_set_mesh_points_3d(n, pts)

    implicit none

    !c passing parameters
    integer :: n
    type(point3d_c),intent(in) :: pts(n)

    !c local variables
    type(c_ptr) :: ptr
    type(point3d_c), dimension(:), pointer :: pts_p
    integer :: i

    !c allocate memory for the points
    ptr = allocate_storage_point3d(n)

    call c_f_pointer(ptr,pts_p,[n])

    do i = 1, n
      pts_p(i) = pts(i)
    end do

    call set_mesh_points_3d(n,ptr)

    !c release memory
    call deallocate_storage(ptr)

  end subroutine cgal_set_mesh_points_3d

  !c 3d triangulation
  subroutine cgal_triangulation_3d

    implicit none

    call triangulation_3d

  end subroutine cgal_triangulation_3d

  !c write mesh to file
  subroutine cgal_output_mesh_3d(strfile,strformat)

    implicit none

    character(len=*) :: strfile, strformat
    character(kind=c_char, len=1), dimension(256) :: strfile_cc, strformat_cc

    integer :: i, nstrfile, nstrformat

    nstrfile = len_trim(strfile)
    nstrformat = len_trim(strformat)

    do i = 1, nstrfile
      strfile_cc(i) = strfile(i:i)
    end do

    do i = 1, nstrformat
      strformat_cc(i) = strformat(i:i)
    end do

    call output_triangulation_3d(nstrfile,strfile_cc,nstrformat,strformat_cc)


  end subroutine cgal_output_mesh_3d

  !c
  !c Example of triangulation test based on scalar points
  !c
  subroutine cgal_triangulation_test_3d

    implicit none

    integer :: ix, iy, iz, n, npts, nx, ny, nz
    type(point3d_c), allocatable :: pts(:)
    character*6 :: strformat
    character*72 :: strfile

    !c set mesh points
    nx = 5
    ny = 5
    nz = 5
    n = nx * ny * nz
    npts = 0
    allocate(pts(n))
    do ix = 1, nx
      do iy = 1, ny
        do iz = 1, nz
          npts = npts + 1
          pts(npts)%x = ix
          pts(npts)%y = iy
          pts(npts)%z = iz
        end do
      end do
    end do

    call cgal_set_mesh_points_3d(npts,pts(1:npts))
    deallocate(pts)

    !c triangulation
    call cgal_triangulation_3d

    !c output mesh information
    write(*,*) "-->check mesh - number of vertices: ", number_of_vertices_3d()
    write(*,*) "-->check mesh - number of edges: ", number_of_edges_3d()
    write(*,*) "-->check mesh - number of facets: ", number_of_facets_3d()
    write(*,*) "-->check mesh - number of cells: ", number_of_cells_3d()

    !c output mesh using "off" format
    strformat = "off"
    strfile = "delaunay"//"."//trim(strformat)
    call cgal_output_mesh_3d(trim(strfile),trim(strformat))

    !c output mesh using "msh" format
    strformat = "msh"
    strfile = "delaunay"//"."//trim(strformat)
    call cgal_output_mesh_3d(trim(strfile),trim(strformat))

  end subroutine cgal_triangulation_test_3d

end module cgal_triangulation_3d_iface

#endif
