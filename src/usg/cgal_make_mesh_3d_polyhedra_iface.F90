module cgal_make_mesh_3d_polyhedra_iface

  !c this is feature of Fortran 2003
  use iso_c_binding

  implicit none

  private

  public cgal_make_mesh_3d_polyhedra_test,                             &
         cgal_initialize_polydomain_3d,                                &
         cgal_set_polydomain_iofile,                                   &
         cgal_make_polydomain_surface_mesh,                            &
         cgal_set_polydomain_criteria,                                 &
         cgal_set_polydomain_opt_params_lloyd,                         &
         cgal_set_polydomain_opt_params_exude,                         &
         cgal_set_polydomain_opt_params_perturb,                       &
         cgal_make_output_polydomain_mesh

  !c interface binding to CGAL c++ code
  interface

    !c initialize domain
    subroutine initialize_polydomain_3d() bind(C,name="initialize_polydomain_3d")
      implicit none
    end subroutine initialize_polydomain_3d

    !c set input file and output file
    subroutine set_polydomain_iofile(lencFileIn, cFileIn,lencFileOut, cFileOut) &
                    bind(C,name="set_polydomain_iofile")
      import c_int, c_char
      implicit none
      integer(c_int), value :: lencFileIn, lencFileOut
      character(kind=c_char, len=1), dimension(lencFileIn) :: cFileIn
      character(kind=c_char, len=1), dimension(lencFileOut) :: cFileOut
    end subroutine set_polydomain_iofile

    !c make surface mesh
    subroutine make_polydomain_surface_mesh() bind(C,name="make_polydomain_surface_mesh")
      implicit none
    end subroutine make_polydomain_surface_mesh

    !c set domain criteria
    subroutine set_polydomain_criteria(edgeSize, facetAngle, facetSize,&
               facetDistance,cellRadiusEdgeRatio, globalSize)          &
               bind(C,name="set_polydomain_criteria")
      import c_double
      implicit none
      real(c_double), value :: edgeSize
      real(c_double), value :: facetAngle
      real(c_double), value :: facetSize
      real(c_double), value :: facetDistance
      real(c_double), value :: cellRadiusEdgeRatio
      real(c_double), value :: globalSize
    end subroutine set_polydomain_criteria

    !c set optimization parameters of Lloyd
    subroutine set_polydomain_opt_params_lloyd(maxIteration,timeLimit) &
                   bind(C,name="set_polydomain_opt_params_lloyd")
      import c_int, c_double
      implicit none
      integer(c_int), value :: maxIteration
      real(c_double), value :: timeLimit
    end subroutine set_polydomain_opt_params_lloyd

