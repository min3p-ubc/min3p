  !c Example of make surface mesh based on domain frame in 'off' file format
  subroutine cgal_make_mesh_3d_test

    implicit none

    character*72 :: strfile        !input domain frame in 'off' file format
    character*72 :: strfile_out    !output domain surface mesh in 'off' file format
    character*6  :: strmesh_format !output mesh format
    character*72 :: domainName     !subdomain name

    !c polyline feature temporatory data
    integer :: n
    logical :: isclosed
    type(point3d_c), allocatable :: pts(:)
    n = 100
    allocate(pts(n))

    !c initialize domain
    call cgal_initialize_domain_3d()
    write(*,*) "initialize domain"

    !c set domain box
    call cgal_set_domain_box_3d(0.0d0, 0.0d0, 0.0d0, 128.0d0, 128.0d0, 128.0d0, 1.0d0, 1.0d0, 1.0d0)
    write(*,*) "set domain box"

    !c set domain criteria
    call cgal_set_domain_criteria_3d(5.0d0, 25.0d0, 5.0d0, 5.0d0, 2.0d0, 5.0d0)
    write(*,*) "set domain criteria"

    !c add subdomain 1
    domainName = "sub-1"
    strfile = "example/usg_3d_multi_domain/multi_domains/subdomain-1.off"
    call cgal_add_subdomain_3d(1, trim(domainName), 5.0d0, strfile)
    write(*,*) "add subdomain 1"

    !c add subdomain 2
    domainName = "sub-2"
    strfile = "example/usg_3d_multi_domain/multi_domains/subdomain-2.off"
    call cgal_add_subdomain_3d(2, trim(domainName), 4.0d0, strfile)
    write(*,*) "add subdomain 2"

    !c add subdomain 3
    domainName = "sub-3"
    strfile = "example/usg_3d_multi_domain/multi_domains/subdomain-3.off"
    call cgal_add_subdomain_3d(3, trim(domainName), 3.0d0, strfile)
    write(*,*) "add subdomain 3"

    !c add subdomain 4
    domainName = "sub-4"
    strfile = "example/usg_3d_multi_domain/multi_domains/subdomain-4.off"
    call cgal_add_subdomain_3d(4, trim(domainName), 2.0d0, strfile)
    write(*,*) "add subdomain 4"

    !c set domain data
    call set_domain_values_3d()
    write(*,*) "set domain data"

    !c make and output image
    strfile = "example/usg_3d_multi_domain/multi_domains/geometry.inr"
    call cgal_make_output_image_3d(trim(strfile))
    write(*,*) "make and output image"

    !c add polyline features
    n = 2
    isclosed = .false.
    pts(1)%x = 0.44
    pts(1)%y = 0.44
    pts(1)%z = 0.44
    pts(2)%x = 0.44
    pts(2)%y = 0.44
    pts(2)%z = 127.05
    call cgal_insert_feature_polyline(n, pts, isclosed)
    pts(1)%x = 127.05
    pts(1)%y = 0.44
    pts(1)%z = 0.44
    pts(2)%x = 127.05
    pts(2)%y = 0.44
    pts(2)%z = 127.05
    call cgal_insert_feature_polyline(n, pts, isclosed)
    pts(1)%x = 127.05
    pts(1)%y = 127.05
    pts(1)%z = 0.44
    pts(2)%x = 127.05
    pts(2)%y = 127.05
    pts(2)%z = 127.05
    call cgal_insert_feature_polyline(n, pts, isclosed)
    pts(1)%x = 0.44
    pts(1)%y = 127.05
    pts(1)%z = 0.44
    pts(2)%x = 0.44
    pts(2)%y = 127.05
    pts(2)%z = 127.05
    call cgal_insert_feature_polyline(n, pts, isclosed)

    !c set optimization parameters
    call cgal_set_domain_opt_params_lloyd(10,10.0d0)
    write(*,*) "set domain mesh Lloyd optimization parameters"


    call cgal_set_domain_opt_params_exude(10.0d0,10.0d0)
    write(*,*) "set domain mesh Exude optimization parameters"


    call cgal_set_domain_opt_params_perturb(10.0d0,10.0d0)
    write(*,*) "set domain mesh Perturb optimization parameters"

    !!c make and output mesh to medit file format
    !strfile_out = "example/multi_domains/geometry_out.mesh"
    !strmesh_format = "mesh"
    !call make_output_mesh_3d(len(trim(strfile)), strfile,              &
    !          len(trim(strfile_out)), strfile_out,                     &
    !          len(trim(strmesh_format)), strmesh_format)
    !write(*,*) "make and output mesh to medit file format"
    !
    !!c make and output mesh to off file format
    !strfile_out = "example/multi_domains/geometry_out.off"
    !strmesh_format = "off"
    !call make_output_mesh_3d(len(trim(strfile)), strfile,              &
    !          len(trim(strfile_out)), strfile_out,                     &
    !          len(trim(strmesh_format)), strmesh_format)
    !write(*,*) "make and output mesh to off file format"
    !
    !!c make and output mesh to msh file format
    !strfile_out = "example/multi_domains/geometry_out.msh"
    !strmesh_format = "msh"
    !call make_output_mesh_3d(len(trim(strfile)), strfile,              &
    !          len(trim(strfile_out)), strfile_out,                     &
    !          len(trim(strmesh_format)), strmesh_format)
    !write(*,*) "make and output mesh to msh file format"

    !c make and output mesh to vtk file format
    strfile_out = "example/usg_3d_multi_domain/multi_domains/geometry_out.vtk"
    strmesh_format = "vtk"
    call cgal_make_output_mesh_3d(strfile, strfile_out, strmesh_format)
    write(*,*) "make and output mesh to msh file format"

    deallocate(pts)

    return

  end subroutine cgal_make_mesh_3d_test

