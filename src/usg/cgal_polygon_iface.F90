#ifdef CGAL

module cgal_polygon_iface

  !c this is feature of Fortran 2003
  use iso_c_binding

  use geometry_definition

  implicit none

  private

  public cgal_is_polygon_simple, cgal_is_polygon_simple_test,          &
         cgal_check_inside, cgal_check_inside_test,                    &
         allocate_storage_point3d, deallocate_storage,                 &
         is_polygon_simple, check_inside


  !c interface binding to CGAL c++ code
  interface

    function allocate_storage_point3d(n) result(iresult) bind(C,name="allocate_storage_point3d")
      import c_int, c_ptr
      implicit none
      integer(c_int),value :: n
      type(c_ptr) :: iresult
    end function allocate_storage_point3d

    subroutine deallocate_storage(ptr) bind(C,name="deallocate_storage")
      import c_ptr
      implicit none
      type(c_ptr), intent(in), value :: ptr
    end subroutine deallocate_storage

    function is_polygon_simple(ixyz,n,pts) result(bflag) bind(C,name="is_polygon_simple")
      import c_int, c_ptr, c_bool
      implicit none
      integer(c_int),value :: ixyz,n
      type(c_ptr), intent(in), value :: pts
      logical(c_bool) :: bflag
    end function

    function check_inside(ixyz,n,pts) result(iflag) bind(C,name="check_inside")
      import c_int, c_ptr
      implicit none
      integer(c_int),value :: ixyz,n
      type(c_ptr), intent(in), value :: pts
      integer(c_int) :: iflag
    end function

  end interface

  !c interface of cgal_is_polygon_simple
  interface cgal_is_polygon_simple
    module procedure cgal_is_polygon_simple_2d
  end interface

  !c interface of cgal_check_inside
  interface cgal_check_inside
    module procedure cgal_check_inside_2d
  end interface

contains
  !>
  !> cgal_is_polygon_simple_2d
  !>   check if a given set of points can construct a simple polygon in the specified projection.
  !>   In geometry a simple polygon is defined as a flat shape consisting of straight,
  !>   non-intersecting line segments or "sides" that are joined pair-wise to form a closed path.
  !> Passing parameters
  !>   ixyz   = 1, projection xy
  !>          = 2, projection yz
  !>          = 3, projection xz
  !>   n      = number of points in the given points set
  !>   pts    = points set array
  !>   bflag  = true if simple polygon and false if not.
  !> Note
  !>   c++ cannot accept fortran allocatable array as the passing variables, instesd,
  !>   it uses pointer to passing the array.
  function cgal_is_polygon_simple_2d(ixyz,n,pts) result(bflag)

    implicit none

    !c passing parameters
    integer :: ixyz,n
    type(point3d_c),intent(in) :: pts(n)
    logical :: bflag

    !c local variables
    type(c_ptr) :: ptr
    type(point3d_c), dimension(:), pointer :: pts_p
    integer :: i

    !c allocate memory
    ptr = allocate_storage_point3d(n)

    call c_f_pointer(ptr,pts_p,[n])

    do i = 1, n
      pts_p(i) = pts(i)
    end do

    bflag = is_polygon_simple(ixyz,n,ptr)

    !c release memory
    call deallocate_storage(ptr)

  end function cgal_is_polygon_simple_2d

  !>
  !> cgal_is_polygon_simple_test, check if the given scalar points can make a polygon.
  !>
  subroutine cgal_is_polygon_simple_test

    implicit none

    logical :: bflag
    type(point3d_c), allocatable :: pts(:)

    !c allocate memory
    allocate(pts(4))

    pts(1)%x = 0.0d0
    pts(1)%y = 0.0d0
    pts(1)%z = 0.0d0

    pts(2)%x = 0.0d0
    pts(2)%y = 2.0d0
    pts(2)%z = 2.0d0

    pts(3)%x = 2.0d0
    pts(3)%y = 0.0d0
    pts(3)%z = 2.0d0

    pts(4)%x = 2.0d0
    pts(4)%y = 2.0d0
    pts(4)%z = 0.0d0

    !c test xy projection
    bflag = cgal_is_polygon_simple_2d(1,4,pts(1:4))
    write(*,*) "Is simple polygon in xy projection: ", bflag

    !c test yz projection
    bflag = cgal_is_polygon_simple_2d(2,4,pts(1:4))
    write(*,*) "Is simple polygon in yz projection: ", bflag

    !c test xz projection
    bflag = cgal_is_polygon_simple_2d(3,4,pts(1:4))
    write(*,*) "Is simple polygon in xz projection: ", bflag

    !c test unknown projection
    bflag = cgal_is_polygon_simple_2d(0,4,pts(1:4))
    write(*,*) "Is simple polygon in unknown projection: ", bflag

    !c correct answer
    write(*,*) "It is simple polygon in xz projection only"

    !c release memory
    deallocate(pts)

  end subroutine cgal_is_polygon_simple_test

  !>
  !> cgal_check_inside_2d
  !>   check if a given point is inside a simple polygon.
  !> Passing parameters
  !>   ixyz   = 1, projection xy
  !>          = 2, projection yz
  !>          = 3, projection xz
  !>   n      = number of points in the given points set
  !>   pts    = points set array
  !>   iflag  = -1, outside of the polygon boundary
  !>          =  0, on the polygon boundary
  !>          =  1, inside of the polygon boundary
  !> Note
  !>   c++ cannot accept fortran allocatable array as the passing variables, instesd,
  !>   it uses pointer to passing the array.
  function cgal_check_inside_2d(ixyz,pt,n,pts) result(iflag)

    implicit none

    !c passing parameters
    integer :: ixyz,n
    type(point3d_c),intent(in) :: pt
    type(point3d_c),intent(in) :: pts(n)
    integer :: iflag

    !c local variables
    type(c_ptr) :: ptr
    type(point3d_c), dimension(:), pointer :: pts_p
    integer :: i

    !c allocate memory
    ptr = allocate_storage_point3d(n+1)

    call c_f_pointer(ptr,pts_p,[n+1])

    pts_p(1) = pt
    do i = 1, n
      pts_p(i+1) = pts(i)
    end do

    iflag = check_inside(ixyz,n+1,ptr)

    !c release memory
    call deallocate_storage(ptr)

  end function cgal_check_inside_2d

  !>
  !> cgal_check_inside_test, check if the given point is inside a simple polygon.
  !>
  subroutine cgal_check_inside_test

    implicit none

    type(point3d_c), allocatable :: pts(:)

    !c local variable
    type(point3d_c) :: pt
    integer :: iflag

    !c allocate memory
    allocate(pts(4))

    pts(1)%x = 0.0d0
    pts(1)%y = 0.0d0
    pts(1)%z = 0.0d0

    pts(2)%x = 2.0d0
    pts(2)%y = 0.0d0
    pts(2)%z = 1.0d0

    pts(3)%x = 2.0d0
    pts(3)%y = 1.0d0
    pts(3)%z = 2.0d0

    pts(4)%x = 0.0d0
    pts(4)%y = 1.0d0
    pts(4)%z = 1.0d0

    !c test xy projection
    pt%x = 1
    pt%y = 3
    pt%z = 1

    iflag = cgal_check_inside_2d(1,pt,4,pts)
    write(*,*) "Is pt inside polygon in xy projection(N): ", iflag

    iflag = cgal_check_inside_2d(2,pt,4,pts)
    write(*,*) "Is pt inside polygon in yz projection(N): ", iflag

    iflag = cgal_check_inside_2d(3,pt,4,pts)
    write(*,*) "Is pt inside polygon in xz projection(Y): ", iflag

    !c release memory
    deallocate(pts)

  end subroutine cgal_check_inside_test

end module cgal_polygon_iface

