    !c insert polyline feature to the domain
    subroutine cgal_insert_feature_polyline(n, pts, isclosed)

      implicit none

      !c passing parameters that will be converted to variables used in C++
      integer :: n
      type(point3d_c), intent(in) :: pts(n)
      logical :: isclosed

      !c local variables
      integer :: i, npts
      type(c_ptr) :: ptr
      type(point3d_c), dimension(:), pointer :: pts_p

      if (isclosed) then
        npts = n + 1
      else
        npts = n
      end if

      !c allocate memory for the points
      ptr = allocate_storage_point3d(npts)

      call c_f_pointer(ptr,pts_p,[npts])

      do i = 1, npts
        pts_p(i) = pts(i)
      end do

      call add_feature_polyline_3d_ex(npts,ptr)

      !c release memory
      call deallocate_storage(ptr)

    end subroutine cgal_insert_feature_polyline

    !c set domain values
    subroutine cgal_set_domain_values_3d()

      implicit none

