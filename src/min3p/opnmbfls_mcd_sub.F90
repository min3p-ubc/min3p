!c ----------------------------------------------------------------------
!c subroutine opnmbfls_mcd
!c -------------------
!c
!c open mass balance files 
!c
!c Based on Pejman Rasouli - March 5, 2012
!c
!c written by:  Danyang Su, May 27, 2025
!c
!c last modified:   -
!c
!c definition of variables:
!c
!c I --> on input   * arbitrary  - initialized  + entries expected
!c O --> on output  * arbitrary  - unaltered    + altered
!c 
!c                                                                    I O
!c passed:   -   
!c
!c common:   
!c gen.f:    integer*4:
!c           ----------
!c           icnv               = unit number, data conversion        + -
!c           ifls               = unit number, file information       + -
!c           imcd               = unit number, mass balance -         * *
!c                                             reactive transport
!c           imcd_first         = pointer - first unit number for     * +
!c                                mass balance - reactive transport
!c           imcd_last          = pointer - last unit number for      * +
!c                                mass balance - reactive transport
!c           imvs               = unit number, mass balance -         * *
!c                                             variably saturated
!c                                             flow
!c           imvs_first         = pointer - first unit number for     * +
!c                                mass balance - variably saturated
!c                                               flow
!c           imvs_last          = pointer - last unit number for      * +
!c                                mass balance - variably saturated
!c                                               flow
!c           l_prfx             = length of prefix of I/O files       + -
!c           nmb                = number of mass balance files for    + -
!c                                selected species
!c
!c           logical:
!c           --------
!c           mass_balance_rt    = .true.  -> compute mass balance     + -
!c                                           (reactive tramsport)
!c           mass_balance_vs    = .true.  -> compute mass balance     + -
!c                                           (variably saturated 
!c                                            flow)
!c
!c           character:
!c           ----------
!c           namemb(nmb)        = names of selected species           + -
!c           prefix             = prefix name for all I/O files       + -
!c           time_unit          = time unit for output -> 'years'     + -
!c                                                        'days'
!c
!c chem.f:   integer*4:
!c           ----------
!c           iaic(nsites)       = pointer array for compressed        + -
!c                                storage of surface site data
!c           nanc               = number of sorbed species            + -
!c           naq                = number of intra-aqueous kinetic     + -
!c                                reactions
!c           nc                 = number of components including h2o  + -
!c           nm                 = number of minerals                  + -
!c           ng                 = number of gases                     + -
!c           nsb                = number of sorbed species            + -
!c           nsb_ion            = number of sorbed species            + -
!c                                (ion-exchange)
!c           nsb_surf           = number of sorbed species            + -
!c                                (surface-complex)
!c           nsites             = number of surface sites             + -
!c
!c           character:
!c           ----------
!c           isotherm_type(nc)  = definition of sorption isotherm     + -    
!c                                'none' = no sorption
!c                                'linear' = linear adsorption
!c                                'freundlich' = Freundlich isotherm
!c                                'langmuir' = Langmuir isotherm
!c           nameanc(nc)        = names of sorbed species             + -
!c                                (non-competitive sorption)
!c           nameaq(naq)        = names of intra-aqueous kinetic      + -
!c                                reactions
!c           namec(nc)          = component names                     + -
!c           nameg(ng)          = names of gases                      + -
!c           namem(nm)          = mineral names                       + -
!c           namesb(nsb)        = names of sorbed species             + -
!c           namesb_ion(nsb_ion)= names of sorbed species             + -
!c                                (ion-exchange)
!c           namesb_surf(nsb_surf)= names of sorbed species           + -
!c                                  (surface-complex)
!c
!c           logical:
!c           --------
!c           noncompetitive_sorption = logical array for activation   + -  
!c                                     of noncompetitive sorption
!c                                     reactions
!c
!c local:    integer*4:
!c           ----------
!c           ianc               = counter (non-competitive sorption
!c                                         reactions)
!c           iaq                = counter (intra-aqueous kinetic 
!c                                         reactions)
!c           ic                 = counter (components)
!c           ig                 = counter (gases)
!c           im                 = counter (minerals)
!c           imb                = counter (selected species)
!c           isb                = counter (sorbed species)
!c           isites             = counter (surface sites)
!c           l_sufx             = length of file suffix
!c
!c           character:
!c           ----------
!c           suffix             = file suffix
!c
!c external: -
!c ----------------------------------------------------------------------
 
      subroutine opnmbfls_mcd_sub

#ifdef PETSC
#include <petscversion.h>
#if (PETSC_VERSION_MAJOR >= 3 && PETSC_VERSION_MINOR >= 8)
#include <petsc/finclude/petscsys.h>
      use petscsys
#endif
#endif

      use parm
      use gen
      use chem
      use file_unit, only : lun_get, lun_set
      use file_utility, only : check_rewind_status
      
      implicit none
#ifdef PETSC
#if (PETSC_VERSION_MAJOR >= 3 && PETSC_VERSION_MINOR >= 6 && PETSC_VERSION_MINOR < 8)
#include <petsc/finclude/petscsys.h>
#elif (PETSC_VERSION_MAJOR >= 3 && PETSC_VERSION_MINOR < 6)
#include <finclude/petscsys.h>
#endif
#endif
      
      integer :: i, ic, imb, isub, l_sufx, ierr

      character*2 suffix
      character*36 :: strl36
      character*256 :: prefix_sub
      character*2048 :: strbuffer      
      integer :: nvarsimcd, ilun, nlun
      logical :: b_rewind_valid
      
      external :: checkerr

!c  only the master processor needs to output mass balance
      if (rank > 0) then
        return
      end if

      if (subdomains_n < 1) then
        return
      end if 

      b_rewind_valid = .false.

 
!c  mass balance - reactive transport - Multicomponent Diffusion Option

      if (flux_out) then

!c  loop over subdomains

        do isub = 1, subdomains_n

          write(prefix_sub,'(a,i0)') "subdomain_", isub
          prefix_sub = trim(prefix_sub)//'/'//prefix(:l_prfx)

          imcd_first(isub) = lun_get()
          nlun = n+2
          do ilun = 1, nlun
            call lun_set(imcd_first(isub)+ilun)
          end do

          if (i_append_sim < 1) then
            write(ifls,'(//72a/2a/72a)') ('*',i=1,72),                         &
                  'subdomain mass balance - reactive transport for ',          &
                  'multicomponent diffusion', ('*',i=1,72)
          end if

!c  total system mass for components

          imcd(isub) = imcd_first(isub)
        
!c  total system mass for selected species

          if (nmb.gt.0) then

            imcd(isub) = imcd(isub) + 1

          end if

!c  contributions to mass balance - aqueous phase

          if (b_enable_output) then
            write(ifls,'(/a/72a/)')'subdomain mass balance - aqueous phase', &
                                   ('-',i=1,72)
            write(ifls,'(2a)') 'file name                           ',   &
                               'component'
          end if
        
          do ic = 1,n

            imcd(isub) = imcd(isub) + 1
          
            if (b_enable_output) then

              if(ic.lt.10) then
                write(suffix,'(i1)') ic
                l_sufx = 1
              elseif (ic.ge.10) then
                write(suffix,'(i2)') ic
                l_sufx = 2
              end if

!c  open file
              b_rewind_valid = check_rewind_status(trim(prefix_sub)//  &
                                     '_'//suffix(:l_sufx)//'.mcd')
              if (b_rewind_valid .and. i_append_sim > 0) then
                open(imcd(isub),file=trim(prefix_sub)//'_'//           &
                        suffix(:l_sufx)//'.mcd',status='unknown',      &
                        form='formatted',position='rewind')
              else
                open(imcd(isub),file=trim(prefix_sub)//'_'//           &
                        suffix(:l_sufx)//'.mcd',status='unknown',      &
                        form='formatted')
              end if
          
!c  version information
              if (i_append_sim < 1 .or. .not.b_rewind_valid) then
                if (b_writeversion_tecplot) then
                  call writeversion2file(imcd(isub), "#")
                end if
              end if
            
              if (i_append_sim < 1 .or. .not.b_rewind_valid) then
                write(imcd(isub),'(3a)') 'title = "dataset ',          &
                      trim(prefix_sub),'"'
  
                write(imcd(isub),'(33a)') 'variables = "time [',       &
                       time_unit(:l_time_unit),']", ',                 &
                      '"influx diffusion [mol/d]", ',                  &
                      '"influx migration [mol/d]", ',                  &
                      '"influx [mol/d]", ',                            &
                      '"outflux diffusion [mol/d]", ',                 &
                      '"outflux migration [mol/d]", ',                 &
                      '"outflux [mol/d]", ',                           &
                      '"change in storage [mol/d]", ',                 &
                      '"source/sink from passive solute uptake [mol/d]", ',&
                      '"accumulative influx diffusion [mol]", ',       &
                      '"accumulative influx migration [mol]", ',       &
                      '"accumulative influx [mol]", ',                 &
                      '"accumulative outflux diffusion [mol]", ',      &
                      '"accumulative outflux migration [mol]", ',      &
                      '"accumulative outflux [mol]", ',                &
                      '"accumulative change in storage [mol]",',       &
                      '"accumulative source/sink from passive solute uptake', &
                      ' [mol]"'
  
                write(imcd(isub),'(4a)')                               &
                      'zone t = "mass balance for component ',         &
                      namec(ic)(:l_namec(ic)),' - ',                   &
                      ' reactive transport", f=point'
              end if

!c  write data to file information file
              strl36 = trim(prefix_sub)//'_'//suffix(:l_sufx)//'.mcd'
              write(ifls,'(2a)') strl36,namec(ic)
            end if
          end do

!c  pointer to last mass balance file for reactive transport

          imcd_last(isub) = imcd(isub)

        end do

      end if

      return
      end
