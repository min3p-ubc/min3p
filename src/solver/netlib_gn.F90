      real*8,save :: ans
      end module test_MOD
!-----------------------------------------------------------------------
      subroutine test_init
      use test_MOD
      use GN_MOD, only:iscale,D0
      implicit none
      integer j
      real*8 del,dx,xi,xmax,xmin
      select case(icase)
      case(1)
         n=2
         m=2
         xstart(1)=-1.2d0
         xstart(2)=1
         ans=0
         xans(1)=1
         xans(2)=1
