  subroutine cgal_set_polydomain_criteria(edgeSize, facetAngle, &
                  facetSize, facetDistance,cellRadiusEdgeRatio, &
                  globalSize)

    implicit none

    real*8, intent(in) :: edgeSize, facetAngle, facetSize,      &
            facetDistance,cellRadiusEdgeRatio, globalSize

    call set_polydomain_criteria(edgeSize, facetAngle,          &
                  facetSize, facetDistance,cellRadiusEdgeRatio, &
                  globalSize)

  end subroutine cgal_set_polydomain_criteria

  !c set optimization parameters of Lloyd
  subroutine cgal_set_polydomain_opt_params_lloyd(maxIteration,timeLimit)
    implicit none
    integer, intent(in) :: maxIteration
    real*8, intent(in) :: timeLimit
    call set_polydomain_opt_params_lloyd(maxIteration,timeLimit)
  end subroutine cgal_set_polydomain_opt_params_lloyd

  !c set optimization parameters of Exude
  subroutine cgal_set_polydomain_opt_params_exude(sliverBound,timeLimit)
    implicit none
    real*8, intent(in) :: sliverBound, timeLimit
    call set_polydomain_opt_params_exude(sliverBound,timeLimit)
  end subroutine cgal_set_polydomain_opt_params_exude

  !c set optimization parameters of Perturb
  subroutine cgal_set_polydomain_opt_params_perturb(sliverBound,timeLimit)
    implicit none
    real*8, intent(in) :: sliverBound, timeLimit
    call set_polydomain_opt_params_perturb(sliverBound,timeLimit)
  end subroutine cgal_set_polydomain_opt_params_perturb

  !c make and output mesh
  subroutine cgal_make_output_polydomain_mesh(cMeshFormat)
    implicit none
    character(len=*), intent(in) :: cMeshFormat
    call make_output_polydomain_mesh(len_trim(cMeshFormat), trim(cMeshFormat))
  end subroutine cgal_make_output_polydomain_mesh

  !c Example of make surface mesh based on domain frame in 'off' file format
  subroutine cgal_make_mesh_3d_polyhedra_test

    implicit none

    character*72 :: strfile        !input domain frame in 'off' file format
    character*72 :: strfile_out    !output domain surface mesh in 'off' file format
    character*6  :: strmesh_format !output mesh format

    logical :: bstat
    integer :: iflag

    strfile = 'domain_polyhedra.off'
    strfile_out = 'domain_polyhedra_out.mesh'
    bstat = .false.
    inquire(file = trim(adjustl(strfile)), exist = bstat)

    if (.not.bstat) then
      write(*,*) "Error: input file does not exist"
      return
    end if

    call cgal_initialize_polydomain_3d()
    write(*,*) "initialize polyhedra domain"


    call cgal_set_polydomain_iofile(strfile, strfile_out)
    write(*,*) "set polyhedra mesh input and output file"


    call cgal_make_polydomain_surface_mesh()
    write(*,*) "make polyhedra domain surface mesh"


    call cgal_set_polydomain_criteria(0.25d0,25.0d0,0.15d0,0.15d0,2.0d0,0.15d0)
    write(*,*) "set polyhedra domain criteria"


    call cgal_set_polydomain_opt_params_lloyd(10,10.0d0)
    write(*,*) "set polyhedra mesh Lloyd optimization parameters"


    call cgal_set_polydomain_opt_params_exude(10.0d0,10.0d0)
    write(*,*) "set polyhedra mesh Exude optimization parameters"


    call cgal_set_polydomain_opt_params_perturb(10.0d0,10.0d0)
    write(*,*) "set polyhedra mesh Perturb optimization parameters"


    strmesh_format = "mesh"
    call cgal_make_output_polydomain_mesh(strmesh_format)
    write(*,*) "make and output polyhedra domain mesh to medit format"

    strmesh_format = "off"
    strfile_out = 'domain_polyhedra_out.off'
    call cgal_set_polydomain_iofile(strfile,strfile_out)
    call cgal_make_output_polydomain_mesh(strmesh_format)
    write(*,*) "make and output polyhedra domain mesh to medit format"

    strmesh_format = "msh"
    strfile_out = 'domain_polyhedra_out.msh'
    call cgal_set_polydomain_iofile(strfile, strfile_out)
    call cgal_make_output_polydomain_mesh(strmesh_format)
    write(*,*) "make and output polyhedra domain mesh to medit format"

    return

  end subroutine cgal_make_mesh_3d_polyhedra_test

end module cgal_make_mesh_3d_polyhedra_iface

