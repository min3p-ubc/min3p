!>
!>  write file information of mimic mass displacement
!>
      subroutine mimicMassDisp_fileCreate

        implicit none

        integer :: i, j, ic, ig, istart, iend 
        logical :: b_rewind_valid
        character(len=1024) :: strbuffer 
        

!cdsu  write the mass of mimic advective gas displacement to file prefix_o.magd
        if (b_enable_output .and. rank == 0) then
          if (nAdvGasDisp > 0) then   
            imagd = lun_get()    

            b_rewind_valid = check_rewind_status(prefix(:l_prfx)//'_o.magd')
            if (b_rewind_valid .and. i_append_sim > 0) then
              open(imagd,file=prefix(:l_prfx)//'_o.magd',status='unknown',&
                   form='formatted',position='rewind')
            else
              open(imagd,file=prefix(:l_prfx)//'_o.magd',status='unknown',&
                   form='formatted')
            end if

            if (i_append_sim < 1 .or. .not.b_rewind_valid) then
              if (b_writeversion_tecplot .and. .not. b_output_trans_binary) then
                call writeversion2file(imagd, "#")
              end if
              write(imagd,'(3a)') 'title = "dataset ',prefix(:l_prfx),'"'
  
              strbuffer = 'variables = "time"'                  
              do j = 1,nAdvGasDisp
                ig = idxAdvGasDisp(j)
                if (mimicAdvGasDisp(ig)) then
                  strbuffer = trim(strbuffer)//', "'//trim(nameg(ig))//'"'

                  istart = iaga(ig)
                  iend = iaga(ig+1)-1
                  do i = istart,iend
                    ic = jaga(i)
                    strbuffer = trim(strbuffer)//', "'//trim(namec(ic))//'"'
                  end do
                end if
              end do
  
              write(imagd,'(a)') trim(strbuffer)
              write(imagd,'(2a)')                                     &
                    'zone t = "system mimic mass displacement", f=point'
            end if

            !c write file information to prefix_o.fls
            write(ifls,'(a/72a/)')'system mimic mass displacement',('-',i=1,72)
            write(ifls,'(a/)') prefix(:l_prfx)//'_o.magd'

            write(ifls,'(2a)') 'column   entry                           ',&
                               'unit'
            write(ifls,'(2a)') '1        time                            ',&
                                time_unit
            
            do j = 1,nAdvGasDisp
              ig = idxAdvGasDisp(j)
              if (2*j.lt.10) then
                write(ifls,'(i1,8x,a30,2x,a)') 2*j,nameg(ig),'mol'
              else
                write(ifls,'(i2,7x,a30,2x,a)') 2*j,nameg(ig),'mol'
              end if
              istart = iaga(ig)
              iend = iaga(ig+1)-1
              do i = istart,iend
                ic = jaga(i)
                if (2*j.lt.9) then
                  write(ifls,'(i1,8x,a30,2x,a)') 2*j+1,namec(ic),'mol'
                else
                  write(ifls,'(i2,7x,a30,2x,a)') 2*j+1,namec(ic),'mol'
                end if
              end do
            end do
          end if
        end if

      end subroutine mimicMassDisp_fileCreate

!>
!>  write mass of mimic advective gas displacement
!>
      subroutine mimicMassDisp_fileWrite

        implicit none

        integer :: ig, irecord

        if (nAdvGasDisp > 0) then 
          if(rank == 0 .and. b_enable_output .and.                       &
             .not.((skip_time.gt.0).and.(nskip_time.lt.skip_time))) then
            if (mtime == mtime_append .and. i_append_sim >= 1) then
              call reposition_file(imagd,irecord)
            end if
  
            if (i_append_sim < 1 .or.                                    &
               (mtime >= mtime_append .and. i_append_sim >= 1)) then
              write(imagd,ascii_fmt) time,(advGasDispBdMass(idxAdvGasDisp(ig)),&
                    advGasAqDispBdMass(idxAdvGasDisp(ig)),ig=1,nAdvGasDisp)
            end if
          end if
        end if

      end subroutine mimicMassDisp_fileWrite

!>
!>  close file of mimic mass displacement
!>
      subroutine mimicMassDisp_fileClose

        implicit none

        if (nAdvGasDisp > 0) then
          close(imagd)
          call lun_free(imagd)
        end if 

      end subroutine mimicMassDisp_fileClose

