      character*100 function GN_infoTxt(info)
! decoded info returned as text function
      implicit none
      integer info,j
      intrinsic btest
      character*100 txt1
      logical btest
      character*25 mess(8)
      data mess/                     &
       "Step < stptol",              &              
       "RelativeImprov < reltol",    &
       " ",                          &
       "F < abstol",                 &
       " ",                          &
       "H sing (no linear uncert)",  &
       " ",                          &
       "Input error"/
! 1   step less than tolerance (stptol).
! 2   relative improvement less than tolerance (reltol).
! 4
! 8   sum of squares less than absolute tolerance (abstol).
! 32  H singular, linear uncertainty calculation not possible.
! 64
! 128 input error.
! 129 Jacobian zero.
! 130 evaluation limit exceeded.
! 133 hook search error.
      write(GN_infoTxt,'(i3,":")') info
      txt1=''
      if(info.eq.0) then
         txt1='no fit'
      elseif(info.eq.129) then
         txt1='Jacobian zero'
      elseif(info.eq.130) then
         txt1='evaluation limit exceeded'
      elseif(info.eq.133) then
         txt1='hook search error'
      else
         do j=1,8
            if(btest(info,j-1)) then
               if(txt1.eq.'') then
                  txt1=trim(mess(j))
               else
                  txt1=trim(txt1)//';'//mess(j)
               endif
            endif
         enddo
      endif
      GN_infoTxt=trim(GN_infoTxt)//trim(txt1)
      END
!-----------------------------------------------------------------------
      subroutine test
! Test GN using More' test problems.
      use GN_MOD, only: abstol,D0,del0,derivstp                      , &
                HistFile,ihist,iHOOKmax,iprint,iscale,iter           , &
                limit,mu0,MXBAD,nconsecMax,NewtStep1st,reltol,stptol , &
                ZCONSEC,ZCP,ZCPMIN,ZHIGH,ZLOW
      use test_MOD
      implicit none
      character*100 GN_infoTxt
      real*8 csq,ftol,sum,x(30),xtol
      integer info,irun,j
      external test_fcn
      data xtol/0.01d0/,ftol/5d-5/
! changes in default values from GN_MOD
      limit=1000000
! changes in default values from test_MOD
      icase1=1
      icase2=36
      nfcnsum=0
      do irun=1,3
         write(*,*)
         if(irun.eq.1) then
            write(*,*)'START NEAR ANSWER'
         elseif(irun.eq.2) then
            write(*,*)'NORMAL START'
         elseif(irun.eq.3) then
            write(*,*)'PERTURBED NORMAL START'
         endif
         write(*,*)'case  m  n nconsec    iter    nfcn   f',           &
           '                          mu       del f X  MaxXerr   info'
         nfcntot=0
         xerrmax=0
         ferrmax=0
         do icase=icase1,icase2
            call test_init
            if(irun.eq.1) xstart=xans-0.001q0 ! start near answer
            x=xstart ! normal starting point for problem icase
            if(irun.eq.3) x=xstart+.04q0 ! perturbed normal start
            nfcn=0
            call GN(test_fcn,m,n,info,x,csq)
            select case(icase)
            case(33)  ! n-1 dimension continuum of answers
               sum=0
               do j=1,n-1
                  xans(j)=x(j)
                  sum=sum+j*x(j)
               enddo
               xans(n)=(3/(2*m+1d0)-sum)/n
            case(34)  ! n-1 dimension continuum of answers
               xans(n)=x(n)
               xans(n-1)=x(n-1)
               sum=0
               do j=1,n-3
                  xans(j)=x(j)
                  sum=sum+j*x(j)
               enddo
               xans(n-2)=(3/(2*m-3d0)-sum)/(n-2)
            case(36) ! this problem is approximately dependent only on x(1)*(1-x(2))
               xans(2)=x(2)
               xans(1)=1.54d0/(1-x(2))
            end select
! update maximum parameter errors
            xerrmax1=0
            do j=1,n
               if(xans(j).gt.0) then
                  xerr=min(abs(x(j)-xans(j)),abs(x(j)-xans(j))/abs(xans(j)))
               else
                  xerr=abs(x(j)-xans(j))
               endif
               if(xerr.gt.xerrmax) then
                  icasexmax=icase
                  jxmax=j
                  xerrmax=xerr
               endif
               if(xerr.gt.xerrmax1) then
                  xerrmax1=xerr
               endif
            enddo
! update maximum function error
            if(ans.gt.0) then
               ferr=min(csq-ans,(csq-ans)/ans)
            else
               ferr=csq-ans
            endif
            if(ferr.gt.ferrmax) then
               icasefmax=icase
               ferrmax=ferr
            endif
            write(*,'(i5,i3,i3,3i8,g22.14,2(1pe10.3),1x,l1,1x,l1,1x,1pe9.2,a100)') &
                  icase,m,n,nconsecMax,iter,nfcn,csq,mu0,del0,ferr.lt.ftol,        &
                  xerrmax1.lt.xtol,xerrmax1,GN_infoTxt(info)
            nfcntot=nfcntot+nfcn
         enddo
         if(xerrmax.gt.xtol.or.ferr.gt.ftol) nfcntot=nfcntot+1000000
! number of millions indicates number of problems with bad results
         write(*,*)'nfcntot=',nfcntot
         nfcnsum=nfcnsum+nfcntot
         write(*,*)'maximum parameter error=',xerrmax,                 &
           ' for icase=',icasexmax,' j=',jxmax
         write(*,*)'maximum function error=',ferrmax,                  &
           ' for icase=',icasefmax
         write(*,*)'derivstp,stptol,limit,abstol,reltol=',             &
           derivstp,stptol,limit,abstol,reltol
         write(*,*)'ZLOW,ZHIGH,ZCP,ZCPMIN,ZCONSEC,MXBAD=',             &
           ZLOW,ZHIGH,ZCP,ZCPMIN,ZCONSEC,MXBAD
         write(*,*)'iscale,NewtStep1st,iHOOKmax=',                     &
           iscale,NewtStep1st,iHOOKmax
      enddo
      write(*,*)'nfcnsum=',nfcnsum
      write(*,*)'ftol,xtol=',ftol,xtol
      end
