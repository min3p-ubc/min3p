#ifdef CGAL

module cgal_polyhedra_iface

  !c this is feature of Fortran 2003
  use iso_c_binding

  implicit none

  private

  public cgal_initialize_polydomain_3d,                                &
         cgal_set_polydomain_iofile,                                   &
         cgal_make_polydomain_surface_mesh,                            &
         cgal_make_polydomain_polyhedra,                               &
         cgal_check_inside_polydomain

  !c interface binding to CGAL c++ code
  interface

    !c initialize domain
    subroutine initialize_polydomain_3d() bind(C,name="initialize_polydomain_3d")
      implicit none
    end subroutine initialize_polydomain_3d

    !c set input file and output file
    subroutine set_polydomain_iofile(lencFileIn, cFileIn,lencFileOut, cFileOut) &
                    bind(C,name="set_polydomain_iofile")
      import c_int, c_char
      implicit none
      integer(c_int), value :: lencFileIn, lencFileOut
      character(kind=c_char, len=1), dimension(lencFileIn) :: cFileIn
      character(kind=c_char, len=1), dimension(lencFileOut) :: cFileOut
    end subroutine set_polydomain_iofile

    !c make surface mesh
    subroutine make_polydomain_surface_mesh() bind(C,name="make_polydomain_surface_mesh")
      implicit none
    end subroutine make_polydomain_surface_mesh

    !c make polyhedra based on triangulated surface mesh
    subroutine make_polydomain_polyhedra() bind(C,name="make_polydomain_polyhedra")
      implicit none
    end subroutine make_polydomain_polyhedra

    !c check if a point is inside, on the boundary or outside of the polyhedra
    function check_inside_polydomain(x,y,z) result(iflag) bind(C,name="check_inside_polydomain")
      import c_double, c_int
      implicit none
      real(c_double), value :: x,y,z
      integer(c_int) :: iflag
    end function check_inside_polydomain

  end interface

contains

  !c initialize polyhedra domain
  subroutine cgal_initialize_polydomain_3d

    implicit none

    call initialize_polydomain_3d()

  end subroutine cgal_initialize_polydomain_3d


  !c set polyhedra mesh input and output
  subroutine cgal_set_polydomain_iofile(strfile,strfile_out)

    implicit none

    character(len=*), intent(in) :: strfile, strfile_out

    call set_polydomain_iofile(len(trim(strfile)), strfile,            &
                               len(trim(strfile_out)), strfile_out)

  end subroutine cgal_set_polydomain_iofile

  !c make polydomain surface mesh
  subroutine cgal_make_polydomain_surface_mesh

    implicit none

    call make_polydomain_surface_mesh()

  end subroutine cgal_make_polydomain_surface_mesh

  !c make polyhedra based on triangulated surface mesh
  subroutine cgal_make_polydomain_polyhedra

    implicit none

    call make_polydomain_polyhedra()

  end subroutine cgal_make_polydomain_polyhedra

  !c check if a point is inside, on the boundary or outside of the polyhedra
  !>   iresult = -1, outside of the polygon boundary
  !>           =  0, on the polygon boundary
  !>           =  1, inside of the polygon boundary
  function cgal_check_inside_polydomain(x,y,z) result(iflag)

    implicit none

    real*8, intent(in) :: x, y, z
    integer :: iflag

    iflag = check_inside_polydomain(x,y,z)

  end function cgal_check_inside_polydomain

  !c Example of make surface mesh based on domain frame in 'off' file format
  subroutine cgal_polyhedra_iface_test

    implicit none

    character*72 :: strfile        !input domain frame in 'off' file format
    character*72 :: strfile_out    !output domain surface mesh in 'off' file format
    character*6  :: strmesh_format !output mesh format

    logical :: bstat
    integer :: iflag

    strfile = 'domain_polyhedra.off'
    strfile_out = 'domain_polyhedra_out.mesh'
    bstat = .false.
    inquire(file = trim(adjustl(strfile)), exist = bstat)

    if (.not.bstat) then
      write(*,*) "Error: input file does not exist"
      return
    end if

    call cgal_initialize_polydomain_3d()
    write(*,*) "initialize polyhedra domain"


    call cgal_set_polydomain_iofile(strfile, strfile_out)
    write(*,*) "set polyhedra mesh input and output file"


    call cgal_make_polydomain_surface_mesh()
    write(*,*) "make polyhedra domain surface mesh"


    call cgal_make_polydomain_polyhedra()
    write(*,*) "make polyhedra based on triangulated surface mesh"

    iflag = -999
    iflag = cgal_check_inside_polydomain(0.0d0,1.0d0,2.0d0)
    write(*,*) "check if point is inside polyhedra domain ", iflag

    return

  end subroutine cgal_polyhedra_iface_test


end module cgal_polyhedra_iface

#endif
